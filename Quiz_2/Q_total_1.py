# ได้ช่องใด ให้นำค่านั้น append ต่อท้ายเข้าไปใน List ของช่องนั้นทันทีโดยไม่ต้องย้ายช่อง

# [ตัวอย่าง Input แบบ 1 บรรทัด] (ตัวสุดท้ายคือขนาดตาราง)
# 10 22 31 4 15 28 17 88 59 11

