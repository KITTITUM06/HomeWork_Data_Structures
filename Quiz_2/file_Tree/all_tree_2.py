# ข้อที่ 4: ตรวจสอบคุณสมบัติ Binary Search Tree (is_BST)
# อ้างอิงสไลด์: 11-Balanced Tree (กิ่งซ้าย < Root < กิ่งขวา)
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขของต้นไม้ Complete Tree
# ตรวจสอบว่ามีคุณสมบัติเป็น BST หรือไม่ (Inorder ต้องเรียงจากน้อยไปมากและไม่ซ้ำกัน)
# แสดงผลลัพธ์: True หรือ False
#
# [ตัวอย่าง Input 1]
# 10 5 15 2 7
# [ตัวอย่าง Output 1]
# True
# (Inorder ได้ 2 5 7 10 15 เรียงลำดับถูกต้อง)
#
# [ตัวอย่าง Input 2]
# 10 15 5
# [ตัวอย่าง Output 2]
# False
# ==============================================================================
def q4_check_is_bst():
    tree = [0] + list(map(int, input().split()))
    size = len(tree) - 1
    inorder_list = []

    def inorder(i):
        if i <= size:
            inorder(i * 2)                  # ซ้าย
            inorder_list.append(tree[i])    # Root
            inorder(i * 2 + 1)              # ขวา

    inorder(1)

    # ตรวจสอบว่าเรียงลำดับจากน้อยไปมากอย่างเคร่งครัดหรือไม่
    is_bst = True
    for i in range(len(inorder_list) - 1):
        if inorder_list[i] >= inorder_list[i + 1]:
            is_bst = False
            break

    print(is_bst)


