# [คำอธิบายโจทย์อย่างละเอียด]
# รับสภาพตารางแฮชที่ลงข้อมูลไว้เรียบร้อยแล้ว และรับค่าเป้าหมาย (target)
# เริ่มค้นหาที่ช่องเริ่มต้น: pos = target % table_size
# - ถ้าช่องนั้นเจอ None ให้หยุดค้นหาทันที (ถือว่าไม่พบข้อมูล)
# - ถ้าเจอค่าไม่ตรง ให้ขยับทีละ 1 ช่องตาม Linear Probing
# แสดงผลลัพธ์ 2 บรรทัด: บรรทัดแรกพบหรือไม่ (True/False), บรรทัดสองจำนวนช่องที่ทำการตรวจ

# [ตัวอย่าง Input แบบ 1 บรรทัด] (ตัวสุดท้ายคือเลข 20 ที่ต้องการค้นหา)
# 77 44 55 20 26 93 17 None None 31 54 20
# [ตัวอย่าง Input แบบ 2 บรรทัด]
# 77 44 55 20 26 93 17 None None 31 54
# 20

# [ตัวอย่าง Output]
# True
# 5
# (20 % 11 = 9 -> เริ่มตรวจช่อง 9 (31), ช่อง 10 (54), ช่อง 0 (77), ช่อง 1 (44), ช่อง 2 (55)... รวมนับตรวจ 5 ครั้ง)
# ------------------------------------------------------------------------------
def q1_7_hash_search_steps():
    # --- กรณีรับ 1 บรรทัด ---
    raw_input = input().split()
    raw_table = raw_input[:-1]
    target = int(raw_input[-1])

    # --- กรณีรับ 2 บรรทัด ---
    # raw_table = input().split()
    # target = int(input().strip())

    table = [None if x == "None" else int(x) for x in raw_table]
    table_size = len(table)
    start_pos = target % table_size

    pos = start_pos
    found = False
    count = 0

    while table[pos] is not None:
        count += 1
        if table[pos] == target:
            found = True
            break
        pos = (pos + 1) % table_size
        if pos == start_pos:
            break

    print(found)
    print(count)


