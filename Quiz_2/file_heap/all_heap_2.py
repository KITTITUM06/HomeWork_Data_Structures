# ข้อที่ 7: นับจำนวนครั้งในการสลับตำแหน่ง (Swap Count) ของการ Insert
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "สลับไปกี่ครั้ง", "จำนวนรอบที่ percolate up", "swap count"
# - ลักษณะโจทย์: ให้ Heap เดิมมาและเลขใหม่ ให้ตอบว่าเลขใหม่ต้องสลับกับพ่อกี่ครั้งกว่าจะหยุด

# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 33 17 27
# 7
# [ตัวอย่าง Output]
# 2
# (อธิบาย: 7 สลับกับ 18 ครั้งที่ 1, แล้วสลับกับ 9 ครั้งที่ 2 จึงหยุดที่ใต้เลข 5)
# ==============================================================================
def q7_count_swap_insert():
    heap = [0] + list(map(int, input().split()))
    new_val = int(input())

    heap.append(new_val)
    i = len(heap) - 1
    swap_count = 0

    while i // 2 > 0:
        if heap[i] < heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            swap_count = swap_count + 1
            i = i // 2
        else:
            break

    print(swap_count)


