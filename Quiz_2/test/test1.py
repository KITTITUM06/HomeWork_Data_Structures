# ข้อที่ 1: Weighted ASCII Hash with Step Value [หมวด Hash Table]
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# รับค่า input บรรทัดเดียว คั่นด้วย spacebar:
# 1. สตริงข้อความ (text)
# 2. ขนาดตารางแฮช (table_size)
# 3. ค่าน้ำหนักเริ่มต้น (start_weight)
# 
# สูตรคำนวณ:
# ตัวอักษรแต่ละตัวคำนวณจาก: ord(c) * (ลำดับตัวอักษร + start_weight)
# โดยลำดับตัวอักษรเริ่มนับจาก 0 (ตัวแรก = 0, ตัวสอง = 1, ...)
# นำผลลัพธ์ของแต่ละตัวมารวมกันเป็น total_sum
# ตำแหน่ง slot ในตาราง = total_sum % table_size
#
# บรรทัดที่ 1: แสดงผลคูณของตัวอักษรแต่ละตัว คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงตำแหน่ง slot ในตาราง
#
# [ตัวอย่าง Input]
# dog 13 2
# (dog คือข้อความ, 13 คือขนาดตาราง, 2 คือค่าน้ำหนักเริ่มต้น)
#
# [การคำนวณเบื้องหลัง (Trace)]
# 'd' (ASCII 100) -> 100 * (0 + 2) = 200
# 'o' (ASCII 111) -> 111 * (1 + 2) = 333
# 'g' (ASCII 103) -> 103 * (2 + 2) = 412
# ผลรวม = 200 + 333 + 412 = 945
# Slot = 945 % 13 = 9
#
# [ตัวอย่าง Output]
# 200 333 412
# 9
# ==============================================================================
def run_mock_q1_weighted_step():
    text, size_str, start_str = input().split()
    table_size = int(size_str)
    start_weight = int(start_str)

    terms = []
    total_sum = 0

    for i in range(len(text)):
        val = ord(text[i]) * (i + start_weight)
        terms.append(str(val))
        total_sum += val

    slot = total_sum % table_size

    print(" ".join(terms))
    print(slot)


