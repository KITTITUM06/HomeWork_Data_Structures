# ข้อที่ 3: TREE นิดนึง - Inorder Traversal บน Complete Binary Tree (Array)
# (ตรงกับ "Tree นิดนึง" โดยใช้ Array ท่องต้นไม้โดยไม่ต้องสร้าง Node Pointer)
# ==============================================================================
# [คำอธิบายโจทย์]
# - รับ input บรรทัดเดียว: ชุดตัวเลขของ Complete Binary Tree เรียงตาม Level-Order
# - แสดงผลลัพธ์: ลำดับการเดินท่องแบบ Inorder (ซ้าย -> Root -> ขวา) คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 10 5 15 2 7
#
# [ตัวอย่าง Output]
# 2 5 7 10 15
# ==============================================================================
def q3_homework_level_tree():
    tree = [0] + list(map(int, input().split()))  # ช่อง 0 เป็น dummy
    size = len(tree) - 1
    result = []

    def inorder(i):
        if i <= size:
            inorder(i * 2)               # เดินไปลูกซ้าย (2*i)
            result.append(str(tree[i]))  # เก็บค่า Root[cite: 4]
            inorder(i * 2 + 1)           # เดินไปลูกขวา (2*i + 1)

    inorder(1)  # เริ่มต้นที่ Root (index 1)
    print(" ".join(result))


