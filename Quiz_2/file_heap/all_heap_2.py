# ข้อที่ 5: ตรวจสอบว่าเป็น Min Heap หรือไม่ (is_min_heap)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "ตรวจสอบฮีพ", "เช็กคุณสมบัติ min heap", "parent <= children เสมอไหม"
# - ลักษณะโจทย์: ให้ชุดตัวเลขมา 1 บรรทัด ให้ตรวจสอบว่าเรียงตามคุณสมบัติ Min Heap หรือไม่
#   ถ้าถูกต้องพิมพ์ True ถ้ามีคู่พ่อลูกที่ผิดกฎ (พ่อ > ลูก) ให้พิมพ์ False
#
# [ตัวอย่าง Input 1]
# 5 9 11 14 18 19 21
# [ตัวอย่าง Output 1]
# True
#
# [ตัวอย่าง Input 2]
# 5 18 11 14 9 19 21
# [ตัวอย่าง Output 2]
# False
# ==============================================================================
def q5_check_min_heap():
    arr = list(map(int, input().split()))
    heap = [0] + arr
    size = len(arr)
    is_heap = True

    # วนลูปเช็กโหนดพ่อทุกตัวที่มีลูก (ตั้งแต่ index 1 ถึง size // 2)
    for i in range(1, (size // 2) + 1):
        left = i * 2
        right = i * 2 + 1

        # เช็กลูกซ้าย: ถ้าพ่อมากกว่าลูกซ้าย ถือว่าผิดกฎ
        if left <= size and heap[i] > heap[left]:
            is_heap = False
            break

        # เช็กลูกขวา: ถ้าพ่อมากกว่าลูกขวา ถือว่าผิดกฎ
        if right <= size and heap[i] > heap[right]:
            is_heap = False
            break

    print(is_heap)

