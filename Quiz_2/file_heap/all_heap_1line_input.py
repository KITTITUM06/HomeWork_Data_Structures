# ข้อที่ 5: ตรวจสอบว่าเป็น Min Heap หรือไม่ (is_min_heap)
# ==============================================================================
# [คำอธิบาย]
# ตรวจสอบว่าโหนดพ่อทุกตัวมีค่าน้อยกว่าหรือเท่ากับลูกซ้ายและลูกขวาเสมอหรือไม่
#
# [ตัวอย่าง Input 1]
# 5 9 11 14 18 19 21
# [ตัวอย่าง Output 1]
# True
# ==============================================================================
def q5_is_min_heap():
    arr = list(map(int, input().split()))
    heap = [0] + arr
    size = len(arr)
    valid = True

    for i in range(1, (size // 2) + 1):
        left = i * 2
        right = i * 2 + 1
        if left <= size and heap[i] > heap[left]:
            valid = False
            break
        if right <= size and heap[i] > heap[right]:
            valid = False
            break

    print(valid)


