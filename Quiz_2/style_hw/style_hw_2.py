# ข้อ 2.2: Insert + percUp (เพิ่มข้อมูลต่อท้ายแล้วดันขึ้น) [เต็ง 2]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# นำค่าใหม่ไปต่อท้ายฮีพ แล้วทำ percUp เปรียบเทียบกับโหนดพ่อที่ดัชนี i // 2
# หากตัวเราน้อยกว่าพ่อ ให้สลับที่กับพ่อขึ้นไปเรื่อยๆ จนถึงตำแหน่งที่ถูกต้อง
# บรรทัดที่ 1: แสดงสภาพ Min Heap หลังการแทรกข้อมูลใหม่เสร็จสิ้น
#
# [ตัวอย่าง Input/Output]
# Input:  5 9 11 14 18 19 21 33 17 27 7
#         (ข้อมูลชุดหน้าคือ Heap เดิม, ตัวเลข 7 ท้ายสุดคือค่าใหม่ที่ต้องการแทรก)
# Output: 5 7 11 14 9 19 21 33 17 27 18
# ------------------------------------------------------------------------------
def run_q2_heap_insert():
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]
    new_val = data[-1]

    heap.append(new_val)
    i = len(heap) - 1

    while i // 2 > 0:
        if heap[i] < heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            i = i // 2
        else:
            break

    print(" ".join(map(str, heap[1:])))


