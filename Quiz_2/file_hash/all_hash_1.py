# ข้อที่ 2: Linear Probing (การหยอดข้อมูลลงตารางแฮชแบบชนแล้วเดินหน้าทีละ 1)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "linear probing", "ชนแล้วหาช่องว่างถัดไป", "วนกลับมาเริ่มที่ 0"
# - ที่มาในสไลด์: หน้า 11-13 สูตร rehash(pos) = (pos + skip) % size ข้ามทีละเท่าไหร่ก็เปลี่ยนที่ skip
    # rehash(pos) = (pos + 1) % size ข้ามทีละ 1 

# [ตัวอย่าง Input]
# 77 44 55 20 26 93 17 31 54
# 11
# (บรรทัดแรก: ลิสต์ตัวเลขที่จะใส่, บรรทัดสอง: ขนาดตารางแฮช)
#
# [ตัวอย่าง Output]
# 77 44 55 20 26 93 17 None None 31 54
# ==============================================================================
def q2_linear_probing():
    items = list(map(int, input().split()))
    table_size = int(input())

    # สร้างตารางเริ่มต้นเป็น None ตามขนาดที่ระบุ
    table = [None] * table_size

    for item in items:
        pos = item % table_size
        # ถ้าช่องนั้นมีข้อมูลอยู่แล้ว ให้ขยับทีละ 1 ช่อง (ถ้าเกินให้วนกลับมาที่ 0)
        while table[pos] is not None:
            pos = (pos + 1) % table_size
        table[pos] = item

    # --- รูปแบบ Output ที่อาจารย์อาจสั่ง (เลือกเปิดใช้) ---
    # แบบที่ A: พิมพ์คั่นด้วย spacebar (แปลง None เป็นตัวหนังสือ "None")
    print(" ".join(map(str, table)))

    # แบบที่ B: พิมพ์แบบเป็น List ดิบของ Python (มีก้ามปู [ ])
    # print(table)

    # แบบที่ C: ช่องว่างพิมพ์เป็น -1 แทน None
    # print(" ".join([str(x) if x is not None else "-1" for x in table]))


