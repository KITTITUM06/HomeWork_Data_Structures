# ข้อ 1.4: Quadratic Probing Insert (กระโดดยกกำลังสอง k^2)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# จัดการการชนโดยการกระโดดด้วยลำดับยกกำลังสองจากตำแหน่งแฮชเดิม h: (h + k^2) % size
# บรรทัดที่ 1: แสดงสภาพตารางแฮชหลังแทรกข้อมูลเสร็จ
# บรรทัดที่ 2: แสดงจำนวนช่องว่าง (None) ที่ยังเหลืออยู่ในตาราง
#
# [ตัวอย่าง Input/Output]
# Input:  77 44 55 20 26 93 17 31 54 11
#         (ตัวท้ายสุด 11 คือขนาดตาราง)
# Output: 77 44 20 55 26 93 17 None None 31 54
#         2
# ------------------------------------------------------------------------------
def run_q1_hash_quadratic_probing():
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    table = [None] * table_size

    for item in items:
        h = item % table_size
        pos = h
        k = 1
        steps = 0
        while table[pos] is not None and steps < table_size:
            pos = (h + (k ** 2)) % table_size
            k += 1
            steps += 1
        if table[pos] is None:
            table[pos] = item

    empty_slots = table.count(None)
    print(" ".join(map(str, table)))
    print(empty_slots)


