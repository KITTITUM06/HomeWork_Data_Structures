# [คีย์เวิร์ดในโจทย์]
# - "ค้นหาในแฮช", "เปรียบเทียบกี่ครั้ง", "เจอหรือหยุดที่ None"
# - ที่มาในสไลด์: หน้า 13 การหาข้อมูลแบบ linear probing ถ้าเจอช่องว่าง (None) ให้ตอบ False ทันที
#
# [ตัวอย่าง Input]
# 77 44 55 20 26 93 17 None None 31 54
# 20
# (บรรทัดแรก: สภาพตารางแฮช, บรรทัดสอง: ค่าที่ต้องการค้นหา)
#
# [ตัวอย่าง Output]
# Found: True
# Comparisons: 5
# (20 เริ่มเช็กที่ช่อง 9 -> 10 -> 0 -> 1 -> 2 -> 3 รวมวิ่งหา 5 ช่อง)
# ==============================================================================
def q5_search_linear_probing():
    raw_table = input().split()
    table = []
    for x in raw_table:
        if x == "None":
            table.append(None)
        else:
            table.append(int(x))

    target = int(input())
    table_size = len(table)
    start_pos = target % table_size

    pos = start_pos
    found = False
    count = 0

    while table[pos] is not None:
        count = count + 1
        if table[pos] == target:
            found = True
            break
        pos = (pos + 1) % table_size
        if pos == start_pos:  # วนกลับมาที่เดิมแล้วยังไม่เจอ
            break

    # --- รูปแบบ Output ---
    # แบบที่ A: แสดงสถานะและจำนวนครั้งที่ตรวจ
    print("Found: " + str(found))
    print("Comparisons: " + str(count))

    # แบบที่ B: แสดงแค่ True / False
    # print(found)


