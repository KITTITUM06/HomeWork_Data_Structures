# ข้อที่ 2: หมวด HEAP (เต็ง 3 - สร้าง Min Heap จาก List ทั้งก้อนด้วย buildHeap)
# อ้างอิงสไลด์: 09-Tree.pdf หน้า 8
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขที่กระจัดกระจายอยู่ คั่นด้วยเว้นวรรค
# สร้าง Min Heap ด้วยวิธี buildHeap ในเวลา O(n) โดยเริ่มทำ percDown จากตำแหน่ง (size // 2) ถอยหลังมาหา 1
# แสดงผลลัพธ์: สภาพ Min Heap หลังจัดเรียงสมบูรณ์ (index 1 ขึ้นไป) คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 9 5 6 2 3
#
# [ตัวอย่าง Output]
# 2 3 6 5 9
# ==============================================================================
def min_child(h, i, size):
    if i * 2 + 1 > size:
        return i * 2
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

def q2_heap_build_heap():
    arr = list(map(int, input().split()))
    size = len(arr)
    heap = [0] + arr  # dummy ที่ index 0

    def perc_down(i):
        while (i * 2) <= size:
            mc = min_child(heap, i, size)
            if heap[i] > heap[mc]:
                heap[i], heap[mc] = heap[mc], heap[i]
                i = mc
            else:
                break

    # เริ่มจากตำแหน่งกึ่งกลาง (ตัวท้ายสุดที่มีลูก) ถอยหลังมาหา Root ตามสไลด์
    i = size // 2
    while i > 0:
        perc_down(i)
        i = i - 1

    print(" ".join(map(str, heap[1:])))


