# ข้อ 2.4: Find Parent & Children Index (คำนวณตำแหน่งเครือญาติใน Heap)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# รับชุดตัวเลขฮีพ และรับดัชนีเป้าหมาย (target) ให้หาค่าของ:
# 1. ลูกซ้าย (Left Child) ที่ตำแหน่ง target * 2
# 2. ลูกขวา (Right Child) ที่ตำแหน่ง target * 2 + 1
# 3. โหนดพ่อ (Parent) ที่ตำแหน่ง target // 2
# หากตำแหน่งใดอยู่นอกขอบเขตของฮีพ ให้แสดงคำว่า None

