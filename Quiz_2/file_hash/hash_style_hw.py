# ข้อที่ 1: การแฮชแบบ ASCII ถ่วงน้ำหนักตำแหน่ง (Weighted String Hash)
# ==============================================================================

# - ข้อความ 1 คำ และขนาดตารางแฮช
# - นำค่า ord(c) ของแต่ละตัวมาคูณกับตำแหน่ง (เริ่มที่ 1) ตามสูตรในสไลด์
# - บรรทัดที่ 1: แสดงค่าผลคูณของแต่ละตัวอักษร คั่นด้วยเว้นวรรค
# - บรรทัดที่ 2: แสดงตำแหน่งช่องแฮช (ผลรวมทั้งหมด mod ด้วยขนาดตาราง)
#
# [ตัวอย่าง Input]
# cat 11
# (c=99*1=99, a=97*2=194, t=116*3=348 -> รวมกันได้ 641, 641 % 11 ได้ 3)
#
# [ตัวอย่าง Output]
# 99 194 348
# 3
# ==============================================================================
def q1_weighted_ascii_hash():
    text, size_str = input().split()
    table_size = int(size_str)

    weighted_values = []
    # คำนวณ ord(c) * ตำแหน่ง (i+1)
    for i in range(len(text)):
        val = ord(text[i]) * (i + 1)
        weighted_values.append(str(val))

    total_sum = sum(map(int, weighted_values))
    slot = total_sum % table_size

    print(" ".join(weighted_values))
    print(slot)


