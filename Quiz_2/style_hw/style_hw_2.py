# ข้อ 2.3: Find Parent & Children Index (คำนวณเครือญาติใน Heap)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# รับข้อมูล Heap และดัชนีเป้าหมาย (target) ให้หาค่าของลูกซ้าย, ลูกขวา และโหนดพ่อ
# สูตร: ลูกซ้าย = 2*i, ลูกขวา = 2*i + 1, พ่อ = i // 2 (ถ้าไม่มีให้ตอบ None)
# บรรทัดที่ 1: แสดงค่าลูกซ้ายและลูกขวา คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงค่าของโหนดพ่อ
#
# [ตัวอย่าง Input/Output]
# Input:  5 9 11 14 18 19 21 2
#         (Heap เดิม, เลข 2 ตัวสุดท้ายคือตรวจสอบที่ดัชนี 2 ซึ่งมีค่าคือ 9)
# Output: 14 18  (ลูกซ้ายดัชนี 4 คือ 14, ลูกขวาดัชนี 5 คือ 18)
#         5      (พ่อดัชนี 1 คือ 5)
# ------------------------------------------------------------------------------
def run_q2_heap_find_relations():
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]
    idx = data[-1]
    size = len(heap) - 1

    parent = heap[idx // 2] if idx // 2 > 0 else "None"
    left = heap[idx * 2] if idx * 2 <= size else "None"
    right = heap[idx * 2 + 1] if idx * 2 + 1 <= size else "None"

    print(str(left) + " " + str(right))
    print(parent)


# ------------------------------------------------------------------------------
# ข้อ 2.4: buildHeap O(n) (สร้าง Min Heap จากลิสต์ทั้งก้อน)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# รับลิสต์ตัวเลขที่ยังไม่ได้จัดระเบียบ นำมาสร้างเป็น Min Heap ในเวลา O(n)
# โดยทำ percDown เริ่มจากโหนดพ่อตัวสุดท้าย (size // 2) วนถอยหลังกลับมาที่ Root (1)
# บรรทัดที่ 1: แสดงสภาพ Min Heap ที่สร้างเสร็จเรียบร้อย
#
# [ตัวอย่าง Input/Output]
# Input:  9 5 6 2 3
# Output: 2 3 6 5 9
# ------------------------------------------------------------------------------
def run_q2_heap_build_heap():
    arr = list(map(int, input().split()))
    size = len(arr)
    heap = [0] + arr

    def perc_down(idx):
        while (idx * 2) <= size:
            mc = min_child(heap, idx, size)
            if heap[idx] > heap[mc]:
                heap[idx], heap[mc] = heap[mc], heap[idx]
                idx = mc
            else:
                break

    i = size // 2
    while i > 0:
        perc_down(i)
        i -= 1

    print(" ".join(map(str, heap[1:])))


