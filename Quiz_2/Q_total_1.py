# ข้อ 2.5: is_min_heap (ตรวจสอบว่า Array ที่ให้มาเป็น Min Heap ที่ถูกต้องหรือไม่)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# ตรวจสอบโครงสร้างฮีพว่าสอดคล้องกับคุณสมบัติ Min Heap หรือไม่
# โดยตรวจสอบเฉพาะโหนดที่มีลูก (ดัชนี 1 ถึง size // 2) ค่าของแม่ต้องน้อยกว่าหรือเท่ากับ
# ทั้งลูกซ้าย (2*i) และลูกขวา (2*i + 1) ทุกจุด[cite: 2]
#
# [ตัวอย่าง Input 1]
# 5 9 11 14 18 19 21
# [ตัวอย่าง Output 1]
# True
#
# [ตัวอย่าง Input 2]
# 5 14 11 9 18 19 21
# [ตัวอย่าง Output 2]
# False
# (ดัชนี 2 มีค่า 14 แต่ลูกซ้ายที่ดัชนี 4 มีค่า 9 ซึ่งลูกน้อยกว่าแม่ ผิดกฎ Min Heap)[cite: 2]
# ------------------------------------------------------------------------------
def q2_5_heap_is_valid_min_heap():
    arr = list(map(int, input().split()))
    heap = [0] + arr
    size = len(arr)
    valid = True

    for i in range(1, (size // 2) + 1):
        left = i * 2
        right = i * 2 + 1
        if left <= size and heap[i] > heap[left]:
            valid = False
            break
        if right <= size and heap[i] > heap[right]:
            valid = False
            break

    print(valid)


