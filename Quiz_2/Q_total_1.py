def q1_6_hash_separate_chaining():
    # --- กรณีรับ 1 บรรทัด ---
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    # --- กรณีรับ 2 บรรทัด ---
    # items = list(map(int, input().split()))
    # table_size = int(input().strip())

    table = [[] for _ in range(table_size)]

    for item in items:
        pos = item % table_size
        table[pos].append(item)

    for idx in range(table_size):
        if len(table[idx]) == 0:
            print(str(idx) + ": Empty")
        else:
            print(str(idx) + ": " + " -> ".join(map(str, table[idx])))


