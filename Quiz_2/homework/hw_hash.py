# โจทย์: ยกกำลังแล้วหาตัวกลาง - EX_25_Exponent_find_center

# [คำอธิบายโจทย์]
# - รับค่า input เป็น int จำนวนสามค่า คั่นด้วย spacebar
#   เป็น ตัวเลข, จำนวนยกกำลัง และจำนวนตัวกลาง
# - หาเลขยกกำลัง และตัวกลางของผลลัพธ์ที่ได้
# - หมายเหตุ: ในกรณีที่ช่วงของตัวกลางไม่พอดี ให้เอาตำแหน่งหน้าตัวกลางมา
#
# [ตัวอย่าง Input 1]
# 44 2 2
# [ตัวอย่าง Output 1]
# 1936
# 93

# [ตัวอย่าง Input 2]
# 35 3 4
# [ตัวอย่าง Output 2]
# 42875
# 4287
# ==============================================================================

base, exp, m_len = map(int, input().split())

# 1. ยกกำลังและแปลงเป็นข้อความ (string)
result = str(base ** exp)

# 2. หา index เริ่มต้นของตัวกลาง
# ใช้สูตร (total_len - m_len) // 2 เพื่อปัดเศษลง (ดึงตำแหน่งหน้ากรณีตัวเลขไม่ลงตัว)
total_len = len(result)
start_idx = (total_len - m_len) // 2
end_idx = start_idx + m_len

# 3. ตัดส่วนตัวกลางออกมาตามช่วง index
middle = result[start_idx:end_idx]

print(result)
print(middle)