# ข้อที่ 3: Linear Probing with Empty Marker [หมวด Collision]
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# รับชุดตัวเลขข้อมูลที่จะหยอดลงตาราง โดยตัวสุดท้ายคือ "ขนาดตารางแฮช"
# ทำการหยอดข้อมูลด้วย Linear Probing (ชนแล้วขยับทีละ 1 ช่อง)
# เงื่อนไขสำคัญ:
# 1. ช่องที่ไม่มีข้อมูล ให้แทนค่าด้วย -1 (ไม่ใช่ None)
# 2. นับเฉพาะ "จำนวนตัวเลขข้อมูล" ที่ต้องเดินหาช่อง (เกิดการชนตั้งแต่ 1 ครั้งขึ้นไป)
#
# บรรทัดที่ 1: แสดงจำนวนตัวเลขที่เกิดการชน (Collided Items Count)
# บรรทัดที่ 2: แสดงสภาพตารางแฮชทั้งหมด คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 12 22 32 4 10
# (ข้อมูลคือ 12 22 32 4, ขนาดตารางคือ 10)
#
# [การคำนวณเบื้องหลัง (Trace)]
# - 12 % 10 = 2 -> ลงช่อง 2 (ไม่ชน)
# - 22 % 10 = 2 -> ชนช่อง 2 ขยับไปช่อง 3 (ชน 1 ตัว)
# - 32 % 10 = 2 -> ชนช่อง 2, 3 ขยับไปช่อง 4 (ชน 1 ตัว)
# - 4 % 10 = 4  -> ชนช่อง 4 ขยับไปช่อง 5 (ชน 1 ตัว)
# รวมตัวเลขที่เคยชน = 3 ตัว (22, 32, 4)
#
# [ตัวอย่าง Output]
# 3
# -1 -1 12 22 32 4 -1 -1 -1 -1
# ==============================================================================
def run_mock_q3_linear_marker():
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    # กำหนดช่องว่างเริ่มต้นเป็น -1 ตามเงื่อนไขโจทย์
    table = [-1] * table_size
    collided_items_count = 0

    for item in items:
        pos = item % table_size
        has_collided = False
        steps = 0

        # วนหาช่องว่างที่ไม่ใช่ -1
        while table[pos] != -1 and steps < table_size:
            has_collided = True
            pos = (pos + 1) % table_size
            steps += 1

        if table[pos] == -1:
            table[pos] = item

        if has_collided:
            collided_items_count += 1

    print(collided_items_count)
    print(" ".join(map(str, table)))


