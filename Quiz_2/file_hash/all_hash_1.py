# ข้อที่ 4: Separate Chaining (การเก็บเป็นลูกโซ่ / ลิสต์ซ้อนลิสต์)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "เก็บเป็นลูกโซ่", "chaining", "append ลงใน list ช่องนั้น"
# - ที่มาในสไลด์: หน้า 16 เมื่อชนกันให้นำไปต่อท้ายลิสต์ในช่องเดิม
#
# [ตัวอย่าง Input]
# 77 44 55 20 26 93 17 31 54
# 11
#
# [ตัวอย่าง Output]
# 0: [77, 44, 55]
# 4: [26]
# 5: [93]
# 6: [17]
# 9: [31, 20]
# 10: [54]
# ==============================================================================
def q4_chaining():
    items = list(map(int, input().split()))
    table_size = int(input())

    # สร้างตารางที่มีช่องเป็นลิสต์เปล่า
    table = []
    for _ in range(table_size):
        table.append([])

    # นำข้อมูลหยอดลงช่องตามค่า mod
    for item in items:
        slot = item % table_size
        table[slot].append(item)

    # --- รูปแบบ Output ที่อาจารย์อาจสั่ง ---
    # แบบที่ A: พิมพ์เฉพาะช่องที่ไม่ว่าง แสดง index และข้อมูล
    for idx in range(table_size):
        if len(table[idx]) > 0:
            print(str(idx) + ": " + str(table[idx]))

    # แบบที่ B: พิมพ์ตารางทั้งหมดแบบ List ซ้อน List
    # print(table)


