# ข้อ 0.2: การบ้าน EX_25_Exponent_find_center (ยกกำลังแล้วหาตัวกลาง)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# รับตัวเลข 3 ค่า คั่นด้วย spacebar คือ: เลขฐาน, กำลัง, และจำนวนหลักของตัวกลาง
# นำเลขฐานมายกกำลัง แล้วหาตัวเลขตรงกลางตามความยาวที่กำหนด[cite: 4]
# หมายเหตุ: หากช่วงของตัวกลางไม่ลงตัวพอดี ให้ปัดลงโดยนำตำแหน่งหน้าตัวกลางมา (// 2)
# บรรทัดที่ 1: แสดงค่าผลลัพธ์ของการยกกำลัง
# บรรทัดที่ 2: แสดงตัวเลขตรงกลางที่ตัดออกมา
#
# [ตัวอย่าง Input/Output]
# Input:  44 2 2
#         (44 คือฐาน, 2 คือยกกำลังสอง, 2 คือเอาตัวกลาง 2 หลัก)
# Output: 1936 (44^2 = 1936 มีความยาว 4 หลัก)
#         93 (จุดเริ่มคือ (4 - 2) // 2 = 1 -> ตัดตำแหน่งที่ 1 ถึง 2 ได้ 93)
# ------------------------------------------------------------------------------
def run_ex25_exponent_find_center():
    base_str, exp_str, center_len_str = input().split()
    base = int(base_str)
    exp = int(exp_str)
    c_len = int(center_len_str)

    val = base ** exp
    s = str(val)

    start = (len(s) - c_len) // 2
    center_val = s[start:start + c_len]

    print(val)
    print(center_val)


