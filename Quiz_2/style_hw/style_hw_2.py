# ข้อ 0.1: การบ้าน EX_24_Folding (วิธีการพับ)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# รับตัวเลขชุดใหญ่และขนาดช่วงการแบ่ง (step) มาในบรรทัดเดียว คั่นด้วย spacebar
# ให้ตัดแบ่งตัวเลขเป็นท่อนๆ ตามความยาว step จากซ้ายไปขวา
# บรรทัดที่ 1: แสดงชิ้นส่วนตัวเลขแต่ละช่วง คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงผลรวมของตัวเลขทุกท่อนที่แบ่งออกมา
#
# [ตัวอย่าง Input/Output]
# Input:  123456789 2
#         (123456789 คือชุดตัวเลข, 2 คือแบ่งท่อนละ 2 หลัก)
# Output: 12 34 56 78 9
#         189 (เกิดจาก 12 + 34 + 56 + 78 + 9)
# ------------------------------------------------------------------------------
def run_ex24_folding():
    num_str, step_str = input().split()
    step = int(step_str)

    chunks = []
    for i in range(0, len(num_str), step):
        chunks.append(num_str[i:i + step])

    total_sum = sum(map(int, chunks))

    print(" ".join(chunks))
    print(total_sum)


