# ข้อ 1.3: Linear Probing Insert (หยอดข้อมูลลงตารางแฮช ชนแล้วขยับทีละ 1) [เต็ง 2]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# กำหนดชุดตัวเลขจำนวนเต็มและขนาดตาราง ให้หยอดตัวเลขลงตารางขนาด table_size
# เริ่มต้นหาตำแหน่งด้วย item % table_size
# หากช่องนั้นว่าง (None) ให้ใส่ข้อมูลลงไปทันที
# หากเกิดการชน (มีข้อมูลอยู่ก่อน) ให้ขยับหาช่องถัดไปทีละ 1 ก้าว: (pos + 1) % table_size
# ทำซ้ำจนกว่าจะเจอช่องว่าง แล้ววางข้อมูลลงไป

# [การคำนวณเบื้องหลัง (Trace)]
# ขนาดตาราง 11:
# 77 % 11 = 0  -> ลงช่อง 0 (ว่าง)
# 44 % 11 = 0  -> ชนช่อง 0 เลื่อนไปช่อง 1 (ว่าง) -> ลงช่อง 1
# 55 % 11 = 0  -> ชนช่อง 0, ชนช่อง 1 เลื่อนไปช่อง 2 (ว่าง) -> ลงช่อง 2

# [ตัวอย่าง Input แบบ 1 บรรทัด] (ตัวสุดท้ายคือขนาดตาราง)
# 77 44 55 20 26 93 17 31 54 11
# [ตัวอย่าง Input แบบ 2 บรรทัด]
# 77 44 55 20 26 93 17 31 54
# 11
#
# [ตัวอย่าง Output]
# 77 44 55 20 26 93 17 None None 31 54
# ------------------------------------------------------------------------------
def q1_3_hash_linear_probing():
    # --- กรณีรับ 1 บรรทัด (ตัวท้ายคือขนาดตาราง) ---
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    # --- กรณีรับ 2 บรรทัด ---
    # items = list(map(int, input().split()))
    # table_size = int(input().strip())

    table = [None] * table_size

    for item in items:
        pos = item % table_size
        steps = 0
        # วนหาช่องว่าง และจำกัดลูปไม่ให้เกิน table_size ป้องกันตารางเต็มแล้วค้าง
        while table[pos] is not None and steps < table_size:
            pos = (pos + 1) % table_size
            steps += 1
        if table[pos] is None:
            table[pos] = item

    print(" ".join(map(str, table)))


