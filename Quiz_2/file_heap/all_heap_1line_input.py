# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 2
# (ตัวเลขหน้าคือ Heap, ตัวสุดท้ายคือเลข 2 หมายถึง index ที่ 2)

# [ตัวอย่าง Output]
# 14 18
# 5
# ==============================================================================
def q4_check_family():
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]
    target = data[-1]
    size = len(heap) - 1

    parent = heap[target // 2] if target // 2 > 0 else "None"
    left = heap[target * 2] if target * 2 <= size else "None"
    right = heap[target * 2 + 1] if target * 2 + 1 <= size else "None"

    # แบบที่ A: บรรทัดแรก Left Right บรรทัดสอง Parent
    print(str(left) + " " + str(right))
