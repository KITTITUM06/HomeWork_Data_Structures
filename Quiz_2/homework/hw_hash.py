# โจทย์: วิธีการพับ (folding) - EX_24_Folding[

# [คำอธิบายโจทย์]
# - รับค่า input เป็น int สองค่า คั่นด้วย spacebar เป็น ชุดตัวเลข และช่วงการแบ่ง
# - แสดงผลลัพธ์การแบ่งช่วง และผลบวกของการแบ่งช่วง

# [ตัวอย่าง Input 1]
# 123456789 2 (2 คือ แบ่งทีละ 2 ตัว)
# [ตัวอย่าง Output 1]
# 12 34 56 78 9
# 189

# [ตัวอย่าง Input 2]
# 4365554698 3
# [ตัวอย่าง Output 2]
# 436 555 469 8
# 1468

# [ตัวอย่าง Input 3]
# 3365984191 4
# [ตัวอย่าง Output 3]
# 3365 9841 91
# 13297
# ==============================================================================

num, fold_size_str = input().split()
fold_size = int(fold_size_str)
chunks = []

# วนลูปหั่นตัวเลขทีละช่วงตามขนาด fold_size
for i in range(0, len(num), fold_size):
    chunks.append(num[i:i + fold_size])

# แปลงแต่ละท่อนเป็น int แล้วนำมาบวกกัน
total_sum = sum(map(int, chunks))
print(" ".join(chunks))
print(total_sum)


