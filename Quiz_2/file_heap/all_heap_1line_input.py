# รวมโค้ดและแนวข้อสอบ: BINARY HEAP (MIN HEAP)

# โครงสร้างหลัก: List โดยช่อง 0 ใส่ dummy 0 ไว้ (Root เริ่มที่ index 1)
# สูตร Index: พ่อ = i // 2 | ลูกซ้าย = 2*i | ลูกขวา = 2*i + 1

# ==============================================================================
# ข้อที่ 1: การเพิ่มข้อมูลใหม่ลงใน Min Heap (Insert & percUp)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - เพิ่มข้อมูล, insert, percolate up, ดันขึ้นบน, นำค่าใหม่ใส่ในฮีพ
# - ที่มาในสไลด์: หน้า 4-5 นำค่าใหม่ไปต่อท้ายสุด แล้วเปรียบเทียบกับพ่อ (i // 2)
#
# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 33 17 27 7
# (ตัวเลขหน้าคือ Heap เดิม, ตัวสุดท้ายคือค่าใหม่ที่จะเพิ่มเข้าไป)
#
# [ตัวอย่าง Output]
# 5 7 11 14 9 19 21 33 17 27 18
# ==============================================================================
def q1_heap_insert():
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]   # ข้อมูล Heap เดิม (Root อยู่ที่ index 1)
    new_val = data[-1]       # ค่าใหม่ที่ต้องการเพิ่ม

    # 1. นำข้อมูลใหม่ไปต่อท้ายสุด
    heap.append(new_val)
    i = len(heap) - 1

    # 2. ดันค่าขึ้นด้านบน (percUp) เปรียบเทียบกับตำแหน่งพ่อ (i // 2)
    while i // 2 > 0:
        if heap[i] < heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            i = i // 2
        else:
            break

    # --- รูปแบบ Output (เลือกปลดคอมเมนต์ตามตัวอย่างโจทย์) ---
    # แบบที่ A: คั่นด้วยเว้นวรรคตั้งแต่ index 1 ถึงตัวสุดท้าย
    print(" ".join(map(str, heap[1:])))

    # แบบที่ B: พิมพ์แบบ List ดิบของ Python
    # print(heap[1:])


