# ข้อที่ 3: [Collision] Quadratic Probing with Step Distance
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# หยอดข้อมูลลงตารางแฮชด้วยวิธี Quadratic Probing เมื่อชนให้กระโดด (h + k^2) % size
# โดยค่า k จะเริ่มนับจาก 1, 2, 3... เพิ่มขึ้นตามลำดับการชน[cite: 1]
# จุดเด่นการรับ Input:
# - ก้อนตัวเลขข้างหน้า = ข้อมูลที่จะหยอด
# - ตัวเลขตัวสุดท้าย = ขนาดตารางแฮช (table_size)
#
# การแสดงผล:
# บรรทัดที่ 1: แสดงระยะกระโดดสูงสุด (ค่า k ที่มากที่สุด) ที่เกิดขึ้นในข้อมูลชุดนี้
#              (หากหยอดแล้วลงช่องว่างได้หมดโดยไม่ชนเลย ให้ตอบ 0)
# บรรทัดที่ 2: แสดงสภาพตารางแฮชทั้งหมด คั่นด้วยเว้นวรรค (ช่องว่างแสดงคำว่า None)
#
# [ตัวอย่าง Input]
# 11 22 33 11
# (ข้อมูลคือ 11 22 33, ขนาดตารางคือ 11)
#
# [การคำนวณเบื้องหลัง (Trace)]
# - 11 % 11 = 0 -> ลงช่อง 0 (ว่าง, k = 0)
# - 22 % 11 = 0 -> ชนช่อง 0 -> ลอง k=1: (0 + 1^2) % 11 = 1 (ว่าง) -> ลงช่อง 1 (ใช้ k = 1)[cite: 1]
# - 33 % 11 = 0 -> ชนช่อง 0 -> ลอง k=1 ชน 22 -> ลอง k=2: (0 + 2^2) % 11 = 4 (ว่าง) -> ลงช่อง 4 (ใช้ k = 2)[cite: 1]
# ค่า k สูงสุดที่เกิดขึ้นคือ 2
#
# [ตัวอย่าง Output]
# 2
# 11 22 None None 33 None None None None None None
# ==============================================================================
def run_mock2_q3_quadratic_max_k():
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    table = [None] * table_size
    max_k = 0

    for item in items:
        h = item % table_size
        pos = h
        k = 0
        steps = 0
        while table[pos] is not None and steps < table_size:
            k += 1
            pos = (h + (k ** 2)) % table_size
            steps += 1
        if table[pos] is None:
            table[pos] = item
        if k > max_k:
            max_k = k

    print(max_k)
    print(" ".join(map(str, table)))


