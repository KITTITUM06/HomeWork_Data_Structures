# รวม TREE TRAVERSAL บน COMPLETE BINARY TREE (ARRAY-BASED)
# โครงสร้าง Complete Binary Tree บน List (เริ่ม index 1 เป็น Root):
# - ลูกซ้าย (Left Child)   = 2 * i
# - ลูกขวา (Right Child)  = 2 * i + 1


# [ตัวอย่าง Input เดียวกันทั้ง 3 แบบ]
# 10 5 15 2 7
# (ต้นไม้: 10 เป็น Root, 5 เป็นลูกซ้าย, 15 เป็นลูกขวา, 2 กับ 7 เป็นลูกของ 5)
# ==============================================================================


# ==============================================================================
# 1. PREORDER TRAVERSAL (Root -> ซ้าย -> ขวา)
# ==============================================================================
# [คำอธิบาย]
# แวะที่ Root ก่อน แล้วจึงเดินท่องกิ่งซ้าย และกิ่งขวาตามลำดับ
#
# [ตัวอย่าง Output]
# 10 5 2 7 15
# ==============================================================================
def preorder_traversal():
    tree = [0] + list(map(int, input().split()))  # index 0 เป็น dummy
    size = len(tree) - 1
    result = []

    def preorder(i):
        if i <= size:
            result.append(str(tree[i]))  # 1. เยี่ยม Root ก่อน
            preorder(i * 2)              # 2. ไปลูกซ้าย (2*i)
            preorder(i * 2 + 1)          # 3. ไปลูกขวา (2*i + 1)

    preorder(1)  # เริ่มต้นที่ Root (index 1)
    print(" ".join(result))


# ==============================================================================
# 2. INORDER TRAVERSAL (ซ้าย -> Root -> ขวา)
# ==============================================================================
# [คำอธิบาย]
# เดินท่องกิ่งซ้ายก่อน แวะที่ Root แล้วจึงเดินท่องกิ่งขวา (ถ้าเป็น BST จะได้เลขเรียงจากน้อยไปมาก)
#
# [ตัวอย่าง Output]
# 2 5 7 10 15
# ==============================================================================
def inorder_traversal():
    tree = [0] + list(map(int, input().split()))
    size = len(tree) - 1
    result = []

    def inorder(i):
        if i <= size:
            inorder(i * 2)               # 1. ไปลูกซ้าย
            result.append(str(tree[i]))  # 2. เยี่ยม Root
            inorder(i * 2 + 1)           # 3. ไปลูกขวา

    inorder(1)
    print(" ".join(result))


# ==============================================================================
# 3. POSTORDER TRAVERSAL (ซ้าย -> ขวา -> Root)
# ==============================================================================
# [คำอธิบาย]
# เดินท่องกิ่งซ้ายและกิ่งขวาให้ครบก่อน แล้วค่อยแวะที่ Root เป็นลำดับสุดท้าย
#
# [ตัวอย่าง Output]
# 2 7 5 15 10
# ==============================================================================
def postorder_traversal():
    tree = [0] + list(map(int, input().split()))
    size = len(tree) - 1
    result = []

    def postorder(i):
        if i <= size:
            postorder(i * 2)             # 1. ไปลูกซ้าย
            postorder(i * 2 + 1)         # 2. ไปลูกขวา
            result.append(str(tree[i]))  # 3. เยี่ยม Root เป็นตัวสุดท้าย

    postorder(1)
    print(" ".join(result))


