# ข้อที่ 3: สร้าง Min Heap จาก List ทั้งก้อน (buildHeap ในเวลา O(n))
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - buildHeap, แปลงชุดตัวเลขเป็นฮีพ, เริ่มจากกึ่งกลางถอยหลังมาที่ 1
# - ที่มาในสไลด์: หน้า 8 เริ่มจาก "คนท้ายสุดที่มีลูก" (size // 2) วิ่งถอยหลังมาหา Root

# [ตัวอย่าง Input]
# 9 5 6 2 3

# [ตัวอย่าง Output]
# 2 3 6 5 9
# ==============================================================================
def q3_build_heap():
    arr = list(map(int, input().split()))
    size = len(arr)
    heap = [0] + arr

    def perc_down(i):
        while (i * 2) <= size:
            mc = min_child(heap, i, size)
            if heap[i] > heap[mc]:
                heap[i], heap[mc] = heap[mc], heap[i]
                i = mc
            else:
                break

    # เริ่มทำจากตัวท้ายสุดที่มีลูก (size // 2) ถอยหลังมาหา index 1
    i = size // 2
    while i > 0:
        perc_down(i)
        i = i - 1

    print(" ".join(map(str, heap[1:])))


