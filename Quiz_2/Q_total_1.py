# [คำอธิบายโจทย์อย่างละเอียด]
# รับ List ข้อมูลที่ยังไม่ได้จัดเรียง นำมาสร้างเป็น Min Heap สมบูรณ์ด้วยเวลา O(n)
# โดยเริ่มต้นทำ percDown จากตำแหน่งกึ่งกลาง (size // 2) ซึ่งเป็นโหนดพ่อตัวสุดท้าย
# ที่ยังมีลูก แล้ววนลูปถอยหลัง (i -= 1) กลับมาหาตำแหน่งที่ 1 (Root)

# [ตัวอย่าง Input แบบ 1 บรรทัด]
# 9 5 6 2 3

# [ตัวอย่าง Output]
# 2 3 6 5 9
# ------------------------------------------------------------------------------
def q2_3_heap_build_heap():
    arr = list(map(int, input().split()))
    size = len(arr)
    heap = [0] + arr

    def perc_down(idx):
        while (idx * 2) <= size:
            mc = min_child(heap, idx, size)
            if heap[idx] > heap[mc]:
                heap[idx], heap[mc] = heap[mc], heap[idx]
                idx = mc
            else:
                break

    # เริ่มทำจากโหนดพ่อตัวสุดท้าย (size // 2) ถอยหลังมาหา Root (1)
    i = size // 2
    while i > 0:
        perc_down(i)
        i -= 1

    print(" ".join(map(str, heap[1:])))


