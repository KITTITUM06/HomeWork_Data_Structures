# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขของต้นไม้ Complete Binary Tree เรียงตาม Level-Order
# ตรวจสอบว่าต้นไม้นี้เป็น Binary Search Tree (BST) หรือไม่
# (ทริก: เดินท่องแบบ Inorder ออกมา ถ้าค่าเรียงจากน้อยไปมาก แปลว่าเป็น BST)
# แสดงผลลัพธ์: True หรือ False
#
# [ตัวอย่าง Input 1]
# 10 5 15 2 7
# [ตัวอย่าง Output 1]
# True
# (Inorder ได้ 2 5 7 10 15 เรียงจากน้อยไปมากอย่างถูกต้อง)
#
# [ตัวอย่าง Input 2]
# 10 15 5
# [ตัวอย่าง Output 2]
# False
# ==============================================================================
def q3_tree_is_bst():
    tree = [0] + list(map(int, input().split()))
    size = len(tree) - 1
    in_order = []

    def inorder(i):
        if i <= size:
            inorder(i * 2)               # ซ้าย
            in_order.append(tree[i])     # Root
            inorder(i * 2 + 1)           # ขวา

    inorder(1)

    # ตรวจสอบว่าลิสต์ in_order เรียงลำดับจากน้อยไปมากหรือไม่
    is_valid = True
    for i in range(len(in_order) - 1):
        if in_order[i] >= in_order[i + 1]:
            is_valid = False
            break

    print(is_valid)


