# ------------------------------------------------------------------------------
# ฟังก์ชันช่วย: คืนดัชนีลูกตัวที่น้อยกว่าสำหรับ Min Heap
# ------------------------------------------------------------------------------
def min_child(h, i, size):
    # กรณีมีลูกคนเดียว (ลูกซ้ายที่ 2*i) ไม่มีลูกขวา
    if i * 2 + 1 > size:
        return i * 2
    # กรณีมีลูก 2 คน เลือกลูกตัวที่ค่าน้อยกว่าเพื่อนำขึ้นมาแทนที่
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

