# ข้อ 2.5: is_valid_min_heap (ตรวจสอบว่า Array เป็น Min Heap ถูกต้องหรือไม่)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# ตรวจสอบว่าชุดตัวเลขใน Array สอดคล้องกับคุณสมบัติของ Min Heap หรือไม่
# แม่ต้องน้อยกว่าหรือเท่ากับลูกเสมอ (ตรวจดัชนี 1 ถึง size // 2)
# บรรทัดที่ 1: แสดง True หรือ False
#
# [ตัวอย่าง Input/Output]
# Input 1:  5 9 11 14 18 19 21  ->  Output: True
# Input 2:  5 14 11 9 18 19 21  ->  Output: False
# ------------------------------------------------------------------------------
def run_q2_heap_is_valid():
    arr = list(map(int, input().split()))
    heap = [0] + arr
    size = len(arr)
    valid = True

    for i in range(1, (size // 2) + 1):
        left = i * 2
        right = i * 2 + 1
        if left <= size and heap[i] > heap[left]:
            valid = False
            break
        if right <= size and heap[i] > heap[right]:
            valid = False
            break

    print(valid)


