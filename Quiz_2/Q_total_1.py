# ข้อ 1.5: Quadratic Probing Insert (ชนแล้วกระโดดยกกำลังสอง: +1^2, +2^2, ...)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# จัดการการชนโดยการกระโดดเป็นลำดับกำลังสองจากตำแหน่งแฮชเดิม (h = item % table_size)
# หากชนครั้งที่ 1 ให้ตรวจที่ (h + 1^2) % table_size
# หากยังชนครั้งที่ 2 ให้ตรวจที่ (h + 2^2) % table_size
# หากยังชนครั้งที่ k ให้ตรวจที่ (h + k^2) % table_size ทำจนกว่าจะพบช่องว่าง[cite: 1]

# [การคำนวณเบื้องหลัง (Trace)]
# ขนาดตาราง 11:
# 77 % 11 = 0 -> ลงช่อง 0
# 44 % 11 = 0 -> ชนช่อง 0 กระโดด (0 + 1^2) % 11 = 1 (ว่าง) -> ลงช่อง 1
# 55 % 11 = 0 -> ชนช่อง 0 กระโดด +1^2 ได้ 1 (ชน 44) -> กระโดด +2^2 ได้ (0 + 4) % 11 = 4 (ว่าง) -> ลงช่อง 4

# [ตัวอย่าง Input แบบ 1 บรรทัด] (ตัวสุดท้ายคือขนาดตาราง)
# 77 44 55 20 26 93 17 31 54 11
# [ตัวอย่าง Output]
# 77 44 20 55 26 93 17 None None 31 54
# ------------------------------------------------------------------------------
def q1_5_hash_quadratic_probing():
    # --- กรณีรับ 1 บรรทัด ---
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    # --- กรณีรับ 2 บรรทัด ---
    # items = list(map(int, input().split()))
    # table_size = int(input().strip())

    table = [None] * table_size

    for item in items:
        h = item % table_size
        pos = h
        k = 1
        steps = 0
        while table[pos] is not None and steps < table_size:
            pos = (h + (k ** 2)) % table_size
            k += 1
            steps += 1
        if table[pos] is None:
            table[pos] = item

    print(" ".join(map(str, table)))


