# ข้อที่ 2: Min Heap delMin and Count Swaps [หมวด Binary Heap]
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# รับชุดตัวเลขของ Min Heap บรรทัดเดียว คั่นด้วย spacebar
# ทำการลบค่าต่ำสุด (Root ดัชนี 1) แล้วนำตัวท้ายสุดขึ้นมาทับ Root
# จากนั้นทำ percDown ดันค่าลงมาเปรียบเทียบกับลูกที่น้อยกว่า (minChild)
# โดยให้นับจำนวนรอบที่มีการ "สลับค่า (Swap)" เกิดขึ้นจริง
#
# บรรทัดที่ 1: แสดงจำนวนครั้งที่มีการสลับค่า (Swaps)
# บรรทัดที่ 2: แสดงสภาพ Min Heap ที่เหลือทั้งหมด คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 3 8 10 12 15 20 25 30 14
#
# [การคำนวณเบื้องหลัง (Trace)]
# ดึง 3 ออก, เอา 14 มาไว้ที่ Root -> [14, 8, 10, 12, 15, 20, 25, 30]
# - รอบที่ 1 ที่ index 1: ลูกน้อยคือ 8 -> 14 มากกว่า 8 -> สลับ (Swap 1)
# - รอบที่ 2 ที่ index 2: ลูกน้อยคือ 12 -> 14 มากกว่า 12 -> สลับ (Swap 2)
# - รอบที่ 3 ที่ index 4: ลูกซ้ายคือ 30 -> 14 น้อยกว่า 30 -> หยุด
# สรุปเกิดการสลับทั้งหมด 2 ครั้ง
#
# [ตัวอย่าง Output]
# 2
# 8 12 10 14 15 20 25 30
# ==============================================================================
def min_child(h, i, size):
    if i * 2 + 1 > size:
        return i * 2
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

def run_mock_q2_delmin_swaps():
    heap = [0] + list(map(int, input().split()))  # dummy 0 ให้ Root = 1
    size = len(heap) - 1

    if size <= 0:
        return

    # เอาตัวท้ายสุดขึ้นมาทับ Root
    heap[1] = heap[size]
    heap.pop()
    size -= 1

    swaps = 0
    i = 1

    # percDown พร้อมนับรอบสลับค่า
    while (i * 2) <= size:
        mc = min_child(heap, i, size)
        if heap[i] > heap[mc]:
            heap[i], heap[mc] = heap[mc], heap[i]
            swaps += 1
            i = mc
        else:
            break

    print(swaps)
    print(" ".join(map(str, heap[1:])))


