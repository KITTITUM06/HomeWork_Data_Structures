# ข้อที่ 6: Max Heap (Insert & Percolate Up) เผื่ออาจารย์เปลี่ยนเป็น Max Heap
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "max heap", "ฮีพค่ามากสุด", "พ่อต้องมากกว่าลูกเสมอ"
# - ลักษณะโจทย์: เหมือนการ Insert ปกติ แต่เงื่อนไขสลับกันคือ ถ้าลูก > พ่อ ให้สลับขึ้นไป

# [ตัวอย่าง Input]
# 50 30 40 10 20 35
# 45
# [ตัวอย่าง Output]
# 50 30 45 10 20 35 40
# ==============================================================================
def q6_max_heap_insert():
    heap = [0] + list(map(int, input().split()))
    new_val = int(input())

    heap.append(new_val)
    i = len(heap) - 1

    # Max Heap: ถ้าตัวลูก (heap[i]) มีค่ามากกว่าพ่อ (heap[i // 2]) ให้สลับขึ้น
    while i // 2 > 0:
        if heap[i] > heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            i = i // 2
        else:
            break

    print(" ".join(map(str, heap[1:])))


