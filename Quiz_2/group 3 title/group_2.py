# ข้อที่ 1: หมวด HASH (เต็ง 1 สไตล์การบ้าน)
# โจทย์: การแฮชสตริงแบบถ่วงน้ำหนักตำแหน่ง (Weighted ASCII Hash)
# อ้างอิงสไลด์: 09,12-Binary Tree and Traversal.pdf หน้า 10
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ข้อความภาษาอังกฤษ 1 คำ และขนาดตารางแฮช
# คำนวณรหัส ASCII คูณด้วยตำแหน่งตัวอักษร (เริ่มตัวแรกคูณ 1) ตามสไลด์
# บรรทัดที่ 1: แสดงผลรวมของค่าถ่วงน้ำหนักทั้งหมด
# บรรทัดที่ 2: แสดงตำแหน่งช่องแฮช (ผลรวม mod ด้วยขนาดตาราง)
#
# [ตัวอย่าง Input]
# cat 11
#
# [ตัวอย่าง Output]
# 641
# 3
# (คำนวณ: 99*1 + 97*2 + 116*3 = 641, แล้ว 641 % 11 ได้ 3)
# ==============================================================================
def q1_hash_weighted_ascii():
    text, table_size_str = input().split()
    table_size = int(table_size_str)

    total_sum = 0
    for i in range(len(text)):
        # นำค่า ASCII ของตัวอักษร คูณด้วยตำแหน่ง (เริ่มคูณที่ 1)
        total_sum = total_sum + (ord(text[i]) * (i + 1))

    slot = total_sum % table_size

    # แสดงผลตาม Output สไลด์
    print(total_sum)
    print(slot)


