# ข้อ 2.6: MAX HEAP delMax & percDown (กรณีโจทย์ดัดแปลงออกเป็น Max Heap)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# สำหรับ Max Heap ค่าที่มากที่สุดจะอยู่ที่ Root (ดัชนี 1)
# เมื่อลบค่าสูงสุดออก จะนำตัวท้ายสุดขึ้นมาไว้ที่ Root แล้วทำ percDown
# โดยสลับที่กับลูกตัวที่ "มีค่ามากกว่า" ลงไปเรื่อยๆ จนกว่าแม่จะมากกว่าลูกทั้งสอง
#
# [ตัวอย่าง Input แบบ 1 บรรทัด]
# 27 18 19 14 9 11 5
#
# [ตัวอย่าง Output]
# 27
# 19 18 11 14 9 5
# ------------------------------------------------------------------------------
def max_child(h, i, size):
    if i * 2 + 1 > size:
        return i * 2
    # สำหรับ Max Heap เลือกลูกตัวที่ "มากกว่า"
    if h[i * 2] > h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

def q2_6_max_heap_delmax():
    heap = [0] + list(map(int, input().split()))
    size = len(heap) - 1
    if size <= 0:
        return

    max_val = heap[1]
    heap[1] = heap[size]
    heap.pop()
    size -= 1

    i = 1
    while (i * 2) <= size:
        mc = max_child(heap, i, size)
        # ถ้าแม่น้อยกว่าลูก ให้สลับลูกตัวโตขึ้นมาแทน
        if heap[i] < heap[mc]:
            heap[i], heap[mc] = heap[mc], heap[i]
            i = mc
        else:
            break

    print(max_val)
    print(" ".join(map(str, heap[1:])))


