# ข้อที่ 3: Quadratic Probing (ชนแล้วกระโดดยกกำลังสอง)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "quadratic probing", "กระโดดแบบยกกำลังสอง", "ชนครั้งแรก +1, ชนครั้งสอง +4, +9"
# - ที่มาในสไลด์: หน้า 15 สูตร rehash(h) = (h + k**2) % size ถ้าเปลี่ยนการยกกำลัง --> ตรงนี้
#
# [ตัวอย่าง Input]
# 77 44 55 20 26 93 17 31 54
# 11
#
# [ตัวอย่าง Output]
# 77 44 20 55 26 93 17 None None 31 54
# ==============================================================================
def q3_quadratic_probing():
    items = list(map(int, input().split()))
    table_size = int(input())

    table = [None] * table_size

    for item in items:
        h = item % table_size
        pos = h
        k = 1
        # ชนครั้งแรก +1^2, ชนครั้งที่สอง +2^2, ชนครั้งที่สาม +3^2
        while table[pos] is not None:
            pos = (h + (k ** 2)) % table_size
            k = k + 1
        table[pos] = item

    # --- รูปแบบ Output ที่อาจารย์อาจสั่ง ---
    # แบบที่ A: พิมพ์คั่นด้วย spacebar
    print(" ".join(map(str, table)))

    # แบบที่ B: พิมพ์แบบ List ดิบ
    # print(table)


