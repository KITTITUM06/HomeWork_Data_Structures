# ข้อที่ 8: ลบค่าต่ำสุดต่อเนื่อง K ครั้ง (DelMin K times / คัดเลือกค่าต่ำสุด K ตัว)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "ลบออก k ครั้ง", "delMin ต่อเนื่อง", "ดึงค่าน้อยสุดออกมา k ลำดับ"
# - ลักษณะโจทย์: บรรทัดแรกให้ Heap มา, บรรทัดที่สองให้จำนวนรอบ k
#   ให้พิมพ์ค่าที่ถูกดึงออกทั้ง k ตัวเรียงตามลำดับที่ดึง
#
# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 33 17 27
# 3
# [ตัวอย่าง Output]
# 5 9 11
# ==============================================================================
def q8_delmin_k_times():
    heap = [0] + list(map(int, input().split()))
    k = int(input())
    size = len(heap) - 1
    removed_items = []

    def get_mc(h, i, cur_size):
        if i * 2 + 1 > cur_size:
            return i * 2
        if h[i * 2] < h[i * 2 + 1]:
            return i * 2
        else:
            return i * 2 + 1

    for _ in range(k):
        if size == 0:
            break
        # 1. หยิบค่า root ออกมาเก็บไว้
        removed_items.append(str(heap[1]))
        # 2. เอาตัวท้ายสุดมาไว้ที่ root
        heap[1] = heap[size]
        heap.pop()
        size = size - 1

        # 3. percDown
        i = 1
        while (i * 2) <= size:
            mc = get_mc(heap, i, size)
            if heap[i] > heap[mc]:
                heap[i], heap[mc] = heap[mc], heap[i]
                i = mc
            else:
                break

    print(" ".join(removed_items))


