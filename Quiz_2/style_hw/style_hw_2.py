# ฟังก์ชันช่วยหาดัชนีลูกตัวที่น้อยกว่าสำหรับ Min Heap
def min_child(h, i, size):
    if i * 2 + 1 > size:
        return i * 2
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1


