# ข้อ 1.5: Linear Probing with Custom Skip (ขยับทีละก้าวที่กำหนด)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# หยอดข้อมูลลงตารางแฮช แต่เมื่อเกิดการชนจะขยับตามระยะก้าว (skip) ที่ระบุใน Input
# สูตร: (pos + skip) % table_size
# บรรทัดที่ 1: แสดงสภาพตารางแฮชทั้งหมด
#
# [ตัวอย่าง Input/Output]
# Input:  77 44 55 20 11 3
#         (ข้อมูลคือ 77 44 55 20, ตัวรองสุดท้าย 11 คือขนาดตาราง, ตัวท้าย 3 คือค่า skip)
# Output: 77 None None 44 None None 55 None None 20 None
# ------------------------------------------------------------------------------
def run_q1_hash_custom_skip():
    data = list(map(int, input().split()))
    items = data[:-2]
    table_size = data[-2]
    skip = data[-1]

    table = [None] * table_size

    for item in items:
        pos = item % table_size
        steps = 0
        while table[pos] is not None and steps < table_size:
            pos = (pos + skip) % table_size
            steps += 1
        if table[pos] is None:
            table[pos] = item

    print(" ".join(map(str, table)))


