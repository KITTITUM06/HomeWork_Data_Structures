# ข้อที่ 2: Folding Hash แบบต่อยอดหา Slot จริง (Fold & Mod Table Size)
# ==============================================================================
# [สไตล์เดียวกับ EX_24_Folding + สไลด์หน้า 8 เรื่อง Folding Method]
# - รับ input 3 ค่า: เลขยาว (num), ขนาดช่วงพับ (fold_size), ขนาดตาราง (table_size)
# - ตัดแบ่งตัวเลขเป็นช่วงๆ และหาผลรวมเหมือนการบ้านข้อที่ 1
# - บรรทัดที่ 1: แสดงผลรวมของท่อนตัวเลขที่แบ่งได้
# - บรรทัดที่ 2: แสดงตำแหน่งช่องแฮช (ผลรวม mod ด้วย table_size)
#
# [ตัวอย่าง Input]
# 4365554698 3 11
# (แบ่งทีละ 3: 436 + 555 + 469 + 8 = 1468, 1468 % 11 ได้ 5)
#
# [ตัวอย่าง Output]
# 1468
# 5
# ==============================================================================
def q2_folding_slot():
    num, fold_size_str, table_size_str = input().split()
    fold_size = int(fold_size_str)
    table_size = int(table_size_str)

    chunks = []
    for i in range(0, len(num), fold_size):
        chunks.append(num[i:i + fold_size])

    total_sum = sum(map(int, chunks))
    slot = total_sum % table_size

    print(total_sum)
    print(slot)


