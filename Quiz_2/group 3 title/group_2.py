# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขใน Min Heap คั่นด้วยเว้นวรรค
# บรรทัดที่ 1: แสดงค่าต่ำสุดที่ถูกลบออก (Root เดิม)
# บรรทัดที่ 2: แสดงสภาพ Min Heap ที่เหลือหลังเลื่อนลงสมบูรณ์ คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 33 17 27
#
# [ตัวอย่าง Output]
# 5
# 9 14 11 17 18 19 21 33 27
# ==============================================================================
def min_child(h, i, size):
    # กรณีมีลูกคนเดียว (ลูกซ้าย)
    if i * 2 + 1 > size:
        return i * 2
    # มีลูก 2 คน เลือกลูกตัวที่ค่าน้อยกว่าเสมอตามรูปสไลด์
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

def q2_heap_delmin():
    heap = [0] + list(map(int, input().split()))  # index 0 ใส่ dummy
    size = len(heap) - 1
    if size == 0:
        return

    min_val = heap[1]             # เก็บค่า Root เดิม
    heap[1] = heap[size]          # นำตัวท้ายสุดมาแทนที่ Root
    heap.pop()                    # เอาช่องท้ายออก
    size = size - 1

    # ทำ percDown เลื่อนลง
    i = 1
    while (i * 2) <= size:
        mc = min_child(heap, i, size)
        if heap[i] > heap[mc]:
            # สลับค่าแม่กับลูกตัวน้อย
            heap[i], heap[mc] = heap[mc], heap[i]
            i = mc
        else:
            break

    print(min_val)
    print(" ".join(map(str, heap[1:])))


