# ข้อ 1.1: Weighted ASCII Hash (การแฮชสตริงแบบถ่วงน้ำหนักตำแหน่ง) [เต็ง 1 สไลด์]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# ให้นำสตริงที่ได้รับมาแปลงค่าเป็นรหัส ASCII ทีละตัวอักษร จากนั้นนำค่า ASCII แต่ละตัว
# มาคูณด้วย "ลำดับตำแหน่งของตัวอักษรนั้น" โดยตำแหน่งแรกเริ่มนับที่ 1, ตำแหน่งสองนับ 2
# นำผลคูณทั้งหมดมารวมกันเป็นผลรวมรวม (Total Sum) แล้วคำนวณหาช่องดัชนี (Slot)
# ในตารางแฮชด้วยการนำ Total Sum ไปมอดุโล (%) ด้วยขนาดตาราง (Table Size)[cite: 1]
#
# [การคำนวณเบื้องหลัง (Trace)]
# สตริง 'cat' ขนาดตาราง 11:
# 'c' (ASCII 99)  คูณตำแหน่ง 1 -> 99 * 1 = 99
# 'a' (ASCII 97)  คูณตำแหน่ง 2 -> 97 * 2 = 194
# 't' (ASCII 116) คูณตำแหน่ง 3 -> 116 * 3 = 348
# ผลรวม (Total Sum) = 99 + 194 + 348 = 641
# ตำแหน่งในตาราง (Slot) = 641 % 11 = 3
#
# [ตัวอย่าง Input แบบ 1 บรรทัด]
# cat 11
# [ตัวอย่าง Input แบบ 2 บรรทัด]
# cat
# 11
#
# [ตัวอย่าง Output]
# 641
# 3
# ------------------------------------------------------------------------------
def q1_1_hash_weighted_ascii():
    # --- กรณีรับ 1 บรรทัด ---
    text, size_str = input().split()
    table_size = int(size_str)

    # --- กรณีรับ 2 บรรทัด (สลับมาใช้ 2 บรรทัดนี้หากโจทย์แยกบรรทัด) ---
    # text = input().strip()
    # table_size = int(input().strip())

    total_sum = 0
    for i in range(len(text)):
        # ord(c) คูณตำแหน่ง (ตัวแรก index 0 คูณ 1, ตัวสอง index 1 คูณ 2)[cite: 1]
        total_sum += ord(text[i]) * (i + 1)

    slot = total_sum % table_size

    print(total_sum)
    print(slot)

