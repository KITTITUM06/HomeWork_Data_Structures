# ข้อที่ 3: หาความสูงและจำนวนชั้นของต้นไม้ (Tree Height & Levels)
# อ้างอิงสไลด์: ความสัมพันธ์จำนวนโหนด N กับความสูง log2(N)
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขของ Complete Binary Tree
# บรรทัดที่ 1: แสดงความสูงของต้นไม้ (Height ถ้านับ Root อยู่ระดับ 0)
# บรรทัดที่ 2: แสดงจำนวนชั้นทั้งหมด (Levels ถ้านับ Root คือชั้น 1)
#
# [ตัวอย่าง Input]
# 10 5 15 2 7
#
# [ตัวอย่าง Output]
# 2
# 3
# ==============================================================================
def q3_tree_height_and_levels():
    import math

    data = list(map(int, input().split()))
    n = len(data)

    if n == 0:
        print(0)
        print(0)
        return

    # คำนวณความสูงตามคณิตศาสตร์ของ Complete Binary Tree
    height = int(math.log2(n))
    levels = height + 1

    print(height)
    print(levels)


