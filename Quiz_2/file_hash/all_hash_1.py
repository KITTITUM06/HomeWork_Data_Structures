# ข้อที่ 1: การแฮชสตริงแบบถ่วงน้ำหนักตำแหน่ง (Weighted ASCII / Anagram Hash)
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - "แฮชตัวอักษร", "ASCII", "ord()", "แก้ปัญหา anagram", "คูณตามตำแหน่ง"
# - ที่มาในสไลด์: หน้า 10 สูตร ord(c) * ตำแหน่ง (เริ่มคูณตำแหน่งที่ 1) แล้วนำผลรวมมา mod

# [ตัวอย่าง Input]
# cat 11
# (คำว่า 'cat' และขนาดตารางคือ 11)

# [ตัวอย่าง Output ตามสไลด์]
# 641
# 3
# (บรรทัดแรก: 99*1 + 97*2 + 116*3 = 641, บรรทัดสอง: 641 % 11 = 3)
# ==============================================================================
def q1_weighted_ascii_hash():
    text, table_size_str = input().split()
    table_size = int(table_size_str)

    total_sum = 0
    # วนลูปนำค่ารหัส ASCII คูณกับตำแหน่ง (pos เริ่มที่ 1)
    for i in range(len(text)):
        total_sum = total_sum + (ord(text[i]) * (i + 1)) #แบบไม่ถ่วงน้ำหนัก  total_sum = total_sum + ord(text[i])

    slot = total_sum % table_size

    # --- รูปแบบ Output ที่อาจารย์อาจสั่ง (เลือกเปิดใช้) ---
    # แบบที่ A: พิมพ์ผลรวม แล้วขึ้นบรรทัดใหม่พิมพ์ slot (ตามสไลด์)
    print(total_sum)
    print(slot)

    # แบบที่ B: พิมพ์เฉพาะ slot ช่องที่ได้ช่องเดียว
    # print(slot)

    # แบบที่ C: พิมพ์ทั้งสองค่าในบรรทัดเดียวคั่นด้วยเว้นวรรค
    # print(str(total_sum) + " " + str(slot))


