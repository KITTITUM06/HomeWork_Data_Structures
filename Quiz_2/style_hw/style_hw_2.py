# ข้อ 1.1: Weighted ASCII Hash (ถ่วงน้ำหนักตำแหน่ง) [เต็ง 1 สไลด์]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# นำตัวอักษรแต่ละตัวมาแปลงเป็นรหัส ASCII แล้วคูณด้วยลำดับตำแหน่ง (ตัวแรกคูณ 1, ตัวสองคูณ 2)
# บรรทัดที่ 1: แสดงค่า intermediate ของแต่ละตัว (ord(c) * ตำแหน่ง) คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงตำแหน่ง slot ในตารางแฮช (ผลรวมทั้งหมด % table_size)
#
# [ตัวอย่าง Input/Output]
# Input:  cat 11
#         (cat คือสตริง, 11 คือขนาดตาราง)
# Output: 99 194 348  (มาจาก 'c'=99*1, 'a'=97*2, 't'=116*3)
#         3           (ผลรวม 641 % 11 = 3)
# ------------------------------------------------------------------------------
def run_q1_hash_weighted_ascii():
    text, size_str = input().split()
    table_size = int(size_str)

    terms = []
    total_sum = 0
    for i in range(len(text)):
        val = ord(text[i]) * (i + 1)
        terms.append(str(val))
        total_sum += val

    slot = total_sum % table_size

    print(" ".join(terms))
    print(slot)


