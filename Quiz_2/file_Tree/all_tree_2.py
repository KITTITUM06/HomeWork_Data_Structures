# ข้อที่ 2: หาบรรพบุรุษทั้งหมดของโหนด (Ancestors / Path to Root)
# อ้างอิงสไลด์: การย้อนกลับหาบรรพบุรุษด้วยสูตร Parent = i // 2
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขต้นไม้ และ "ตัวสุดท้ายคือ index เป้าหมาย"
# แสดงผลลัพธ์: ลำดับค่าบรรพบุรุษจากพ่อวิ่งย้อนกลับไปถึง Root คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 10 5 15 2 7 5
# (ต้นไม้คือ 10 5 15 2 7, ตัวสุดท้ายคือเลข 5 หมายถึง index ที่ 5 ซึ่งคือค่า 7)
#
# [ตัวอย่าง Output]
# 5 10
# (พ่อของ 7 คือ 5 อยู่ที่ index 2, พ่อของ 5 คือ 10 ซึ่งเป็น Root)
# ==============================================================================
def q2_ancestors_to_root():
    data = list(map(int, input().split()))
    tree = [0] + data[:-1]
    target_idx = data[-1]

    path = []
    curr = target_idx // 2  # เริ่มต้นที่ตำแหน่งพ่อของตัวเอง

    while curr > 0:
        path.append(str(tree[curr]))
        curr = curr // 2    # ถอยกลับไปหาปู่ ย่า ตา ทวด เรื่อยๆ

    # ถ้าโจทย์ให้แสดงแบบมีลูกศร ให้แก้เป็น: print(" -> ".join(path))
    print(" ".join(path))


