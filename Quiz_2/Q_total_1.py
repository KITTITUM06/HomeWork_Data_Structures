# 2

# [ตัวอย่าง Output]
# 14 18
# 5
# (ที่ดัชนี 2 ค่าคือ 9 มีลูกซ้ายดัชนี 4 คือ 14, ลูกขวาดัชนี 5 คือ 18, พ่อดัชนี 1 คือ 5)
# ------------------------------------------------------------------------------
