# ข้อที่ 1: แยกแยะโหนดใบ (Leaf Nodes) กับ โหนดภายใน (Internal Nodes)
# อ้างอิงสไลด์: นิยาม Leaf Node (ไม่มีลูก) และ Internal Node (มีลูกอย่างน้อย 1 คน)
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขของ Complete Binary Tree เรียงตาม Level-Order
# บรรทัดที่ 1: แสดงค่าของ Leaf Nodes ทั้งหมด คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงค่าของ Internal Nodes ทั้งหมด คั่นด้วยเว้นวรรค
# (สูตร: โหนดที่มีลูกคือ index 1 ถึง size // 2, นอกนั้นคือโหนดใบ)
#
# [ตัวอย่าง Input]
# 10 5 15 2 7
#
# [ตัวอย่าง Output]
# 15 2 7
# 10 5
# ==============================================================================
def q1_leaf_and_internal():
    tree = [0] + list(map(int, input().split()))
    size = len(tree) - 1

    leaf_nodes = []
    internal_nodes = []

    for i in range(1, size + 1):
        # ถ้าตำแหน่งลูกซ้าย (2*i) เกินขนาดต้นไม้ แปลว่าไม่มีลูกเลย เป็น Leaf
        if i * 2 > size:
            leaf_nodes.append(str(tree[i]))
        else:
            internal_nodes.append(str(tree[i]))

    # --- รูปแบบ Output (ปรับตามที่โจทย์สั่ง) ---
    print(" ".join(leaf_nodes))
    print(" ".join(internal_nodes))


