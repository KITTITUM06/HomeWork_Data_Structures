# ข้อ 2.1: delMin + percDown [เต็ง 1 สไลด์หน้าโน้ตสีแดง # Quiz Heap]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# นำค่าต่ำสุดที่ Root (ดัชนี 1) ออกมา จากนั้นเอาโหนดตัวสุดท้ายของฮีพขึ้นมาวางแทนที่
# แล้วทำกระบวนการ percDown ดันค่าลงไปด้านล่างโดยสลับที่กับลูกตัวที่น้อยกว่าเรื่อยๆ
# บรรทัดที่ 1: แสดงค่าต่ำสุด (min_val) ที่ถูกลบออก
# บรรทัดที่ 2: แสดงสภาพ Min Heap ที่เหลือทั้งหมดหลังจัดระเบียบเรียบร้อย
#
# [ตัวอย่าง Input/Output]
# Input:  5 9 11 14 18 19 21 33 17 27
# Output: 5
#         9 14 11 17 18 19 21 33 27
# ------------------------------------------------------------------------------
def run_q2_heap_delmin():
    heap = [0] + list(map(int, input().split()))  # ช่อง 0 เป็น dummy
    size = len(heap) - 1

    if size <= 0:
        return

    min_val = heap[1]
    heap[1] = heap[size]
    heap.pop()
    size -= 1

    i = 1
    while (i * 2) <= size:
        mc = min_child(heap, i, size)
        if heap[i] > heap[mc]:
            heap[i], heap[mc] = heap[mc], heap[i]
            i = mc
        else:
            break

    print(min_val)
    print(" ".join(map(str, heap[1:])))


