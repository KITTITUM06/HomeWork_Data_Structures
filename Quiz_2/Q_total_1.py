# จากนั้นนำผลรวมไปมอดุโล (%) ด้วยขนาดตารางแฮช

# [การคำนวณเบื้องหลัง (Trace)]
# สตริง 'cat' ขนาดตาราง 11:
# 'c' (99) + 'a' (97) + 't' (116) = 312
# Slot = 312 % 11 = 4

# [ตัวอย่าง Input แบบ 1 บรรทัด]
# cat 11
