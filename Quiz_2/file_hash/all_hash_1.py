# hash เอาขนาดของตาราง hash มา mod ได้เลย
# h(item) = item % n
# วิธีการพับ (folding) --> แบ่งเลขเป็นช่วงๆ บวกกัน แล้ว mod (เหมือนการบ้าน)
# ตัวกลางยกกำลัง (mid sqare method) --> ยกกำลังแล้ว  เอาตัวกลางไป mod
