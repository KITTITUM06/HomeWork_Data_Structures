# ข้อที่ 1: HASH - แปลงสตริงเป็นรหัส ASCII แล้วหาผลรวมและช่องตาราง
# (ล้อตามการบ้าน Folding/Mid-Square และสไลด์ Hashing หน้า 10)
# ==============================================================================
# [คำอธิบายโจทย์]
# - รับ input บรรทัดเดียว: ข้อความภาษาอังกฤษ และขนาดตารางแฮช คั่นด้วยเว้นวรรค
# - บรรทัดที่ 1: แสดงรหัส ASCII ของแต่ละตัวอักษร คั่นด้วยเว้นวรรค
# - บรรทัดที่ 2: แสดงตำแหน่งช่อง (ผลรวม ASCII ทั้งหมด mod ด้วยขนาดตาราง)
#
# [ตัวอย่าง Input]
# cat 11
#
# [ตัวอย่าง Output]
# 99 97 116
# 4
# ==============================================================================
def q1_homework_level_hash():
    text, size_str = input().split()
    table_size = int(size_str)

    ascii_list = []
    # แปลงตัวอักษรแต่ละตัวเป็นรหัส ASCII ด้วย ord()
    for char in text:
        ascii_list.append(str(ord(char)))

    total_sum = sum(map(int, ascii_list))
    slot = total_sum % table_size

    print(" ".join(ascii_list))
    print(slot)


