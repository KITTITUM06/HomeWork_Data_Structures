# ข้อที่ 2: การลบค่าน้อยสุดและเลื่อนลง (delMin & percDown)
# *จุดเต็งในสไลด์หน้า 7 ที่อาจารย์เขียน "Quiz Heap" เน้น minChild ค่าน้อยสุด*
# ==============================================================================
# [คีย์เวิร์ดในโจทย์]
# - ลบค่าน้อยสุด, delMin, remove min, percolate down, เลื่อนลงล่าง, minChild
# - ลักษณะการทำงาน: นำตัวท้ายสุดขึ้นมาแทนที่ Root แล้วเลื่อนลงโดยสลับกับลูกที่ค่าน้อยกว่า
#
# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 33 17 27

# [ตัวอย่าง Output ตามสไลด์]
# 5
# 9 14 11 17 18 19 21 33 27
# ==============================================================================
def min_child(h, i, size):
    # กรณีมีลูกซ้ายคนเดียว (ไม่มีลูกขวา)
    if i * 2 + 1 > size:
        return i * 2
    # กรณีมีทั้งสองลูก เลือกลูกตัวที่ค่าน้อยกว่าเสมอ
    if h[i * 2] < h[i * 2 + 1]:
        return i * 2
    else:
        return i * 2 + 1

def q2_heap_delmin():
    heap = [0] + list(map(int, input().split()))
    size = len(heap) - 1
    if size == 0:
        return

    min_val = heap[1]             # เก็บค่า Root เดิมไว้
    heap[1] = heap[size]          # นำตัวท้ายสุดมาแทนที่ Root
    heap.pop()                    # ลบช่องท้ายออก
    size = size - 1

    # ดันค่าลงข้างล่าง (percDown)
    i = 1
    while (i * 2) <= size:
        mc = min_child(heap, i, size)
        if heap[i] > heap[mc]:
            heap[i], heap[mc] = heap[mc], heap[i]
            i = mc
        else:
            break

    # --- รูปแบบ Output ---
    # แบบที่ A: บรรทัดแรกพิมพ์ค่าที่ลบ บรรทัดสองพิมพ์ heap ที่เหลือ (ตามสไลด์)
    print(min_val)
    print(" ".join(map(str, heap[1:])))

    # แบบที่ B: พิมพ์เฉพาะสภาพ Heap ที่เหลือบรรทัดเดียว
    # print(" ".join(map(str, heap[1:])))

    # แบบที่ C: เอาเฉพาะค่าต่ำสุดที่ถูกลบออกเพียงค่าเดียว
