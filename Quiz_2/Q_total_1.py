# ข้อ 1.4: Linear Probing with Custom Skip (ชนแล้วขยับตามระยะก้าวที่กำหนด)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# หยอดข้อมูลลงตารางแฮชเหมือน Linear Probing แต่เมื่อเกิดการชน จะไม่ขยับทีละ 1
# แต่จะขยับตามค่าคงที่ skip ที่กำหนด: (pos + skip) % table_size

# [ตัวอย่าง Input แบบ 1 บรรทัด]
# 77 44 55 20 11 3
# (ตัวเลขชุดหน้าคือข้อมูล, ตัวรองสุดท้าย 11 คือ table_size, ตัวสุดท้าย 3 คือค่า skip)

# [ตัวอย่าง Output]
# 77 None None 44 None None 55 None None 20 None
# ------------------------------------------------------------------------------
def q1_4_hash_linear_custom_skip():
    # --- กรณีรับ 1 บรรทัด ---
    data = list(map(int, input().split()))
    items = data[:-2]
    table_size = data[-2]
    skip = data[-1]

    # --- กรณีรับ 2 บรรทัด (บรรทัดแรกข้อมูล, บรรทัดสอง: size skip) ---
    # items = list(map(int, input().split()))
    # table_size, skip = map(int, input().split())

    table = [None] * table_size

    for item in items:
        pos = item % table_size
        steps = 0
        while table[pos] is not None and steps < table_size:
            pos = (pos + skip) % table_size
            steps += 1
        if table[pos] is None:
            table[pos] = item

    print(" ".join(map(str, table)))


