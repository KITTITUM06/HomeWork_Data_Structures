# ข้อ 2.1: delMin + percDown (ลบค่าน้อยสุดและเลื่อนลง) [เต็ง 1 สไลด์หน้า # Quiz Heap]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# ลบค่าที่น้อยที่สุดออกจาก Min Heap (ซึ่งอยู่ที่ Root คือดัชนี 1)
# 1. บันทึกค่าต่ำสุดเดิมไว้ที่ min_val
# 2. นำข้อมูลโหนดตัวสุดท้ายของฮีพ (ดัชนีท้ายสุด) ย้ายขึ้นมาวางทับที่ Root (ดัชนี 1)
# 3. ลบโหนดสุดท้ายทิ้ง และลดขนาดฮีพลง 1
# 4. ทำ percDown จากโหนด 1 ลงไปด้านล่าง โดยเปรียบเทียบกับลูกที่น้อยกว่า (minChild)
#    ถ้าตัวแม่มากกว่าลูกตัวน้อย ให้สลับที่กัน แล้วเลื่อนลงไปตรวจสอบต่อเรื่อยๆ[cite: 2]
# แสดงผลลัพธ์ 2 บรรทัด: บรรทัดแรกคือค่าที่ถูกลบออก, บรรทัดสองคือสภาพฮีพใหม่
#
# [ตัวอย่าง Input แบบ 1 บรรทัด]
# 5 9 11 14 18 19 21 33 17 27
#
# [ตัวอย่าง Output]
# 5
# 9 14 11 17 18 19 21 33 27
# ------------------------------------------------------------------------------
def q2_1_heap_delmin():
    heap = [0] + list(map(int, input().split()))  # ใส่ dummy 0 เพื่อให้ Root เริ่มดัชนี 1[cite: 2]
    size = len(heap) - 1
    if size <= 0:
        return

    min_val = heap[1]             # ค่าต่ำสุดอยู่ที่ Root[cite: 2]
    heap[1] = heap[size]          # นำตัวท้ายสุดมาแทนที่ Root
    heap.pop()                    # ตัดตัวท้ายสุดทิ้ง
    size -= 1

    # ดันค่าลง (percDown) ตามสไลด์ที่อาจารย์เน้น[cite: 2]
    i = 1
    while (i * 2) <= size:
        mc = min_child(heap, i, size)
        if heap[i] > heap[mc]:    # ถ้าตัวแม่มากกว่าลูก ให้สลับค่ากัน[cite: 2]
            heap[i], heap[mc] = heap[mc], heap[i]
            i = mc
        else:
            break

    print(min_val)
    print(" ".join(map(str, heap[1:])))


