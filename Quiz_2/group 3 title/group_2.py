# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลข Complete Binary Tree เรียงตาม Level-Order
# แสดงผลลัพธ์: ลำดับการท่องต้นไม้ คั่นด้วยเว้นวรรค (ตัวอย่างนี้ตั้งค่าเริ่มต้นเป็น Inorder)
#
# [ตัวอย่าง Input]
# 10 5 15 2 7
#
# [ตัวอย่าง Output (Inorder: ซ้าย -> Root -> ขวา)]
# 2 5 7 10 15
# ==============================================================================
def q3_tree_traversal():
    tree = [0] + list(map(int, input().split()))  # index 0 เป็น dummy
    size = len(tree) - 1
    result = []

    # ฟังก์ชันท่องต้นไม้ (สลับลำดับบรรทัด append ได้ตามที่โจทย์สั่ง)
    def inorder(i):
        if i <= size:
            inorder(i * 2)               # เดินไปลูกซ้าย (2*i)
            result.append(str(tree[i]))  # เก็บ Root (ถ้า Preorder ย้ายมาไว้บรรทัดนี้)
            inorder(i * 2 + 1)           # เดินไปลูกขวา (2*i + 1)
            # (ถ้า Postorder ให้ย้าย append มาไว้ล่างสุด)

    inorder(1)
    print(" ".join(result))


