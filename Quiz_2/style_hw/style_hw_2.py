# ข้อ 1.2: Simple ASCII Hash (บวก ASCII ตรงๆ ไม่คูณตำแหน่ง)
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# แปลงตัวอักษรแต่ละตัวในสตริงเป็นรหัส ASCII ตรงๆ แล้วนำมารวมกัน
# บรรทัดที่ 1: แสดงค่า ASCII ของตัวอักษรแต่ละตัว คั่นด้วยเว้นวรรค
# บรรทัดที่ 2: แสดงตำแหน่ง slot ในตารางแฮช (ผลรวมทั้งหมด % table_size)
#
# [ตัวอย่าง Input/Output]
# Input:  cat 11
# Output: 99 97 116
#         4           (ผลรวม 312 % 11 = 4)
# ------------------------------------------------------------------------------
def run_q1_hash_simple_ascii():
    text, size_str = input().split()
    table_size = int(size_str)

    ascii_vals = [str(ord(c)) for c in text]
    slot = sum(map(int, ascii_vals)) % table_size

    print(" ".join(ascii_vals))
    print(slot)


