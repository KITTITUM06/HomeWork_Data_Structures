# ข้อที่ 3: Mid-Square Hash แบบต่อยอดหา Slot จริง (Square, Cut Center & Mod)
# ==============================================================================

# - รับ input 3 ค่า: key (ตัวเลขหลัก), m_len (จำนวนหลักตัวกลาง), table_size
# - นำ key มายกกำลัง 2 แล้วตัดตัวกลางออกมาเหมือนการบ้านข้อที่ 2
# - บรรทัดที่ 1: แสดงตัวเลขส่วนตรงกลางที่ตัดออกมาได้
# - บรรทัดที่ 2: แสดงตำแหน่งช่องแฮช (เลขตรงกลาง mod ด้วย table_size)
#
# [ตัวอย่าง Input]
# 44 2 11
# (44^2 = 1936, ดึงตัวกลาง 2 หลักได้ 93, 93 % 11 ได้ 5)
#
# [ตัวอย่าง Output]
# 93
# 5
# ==============================================================================
def q3_midsquare_slot():
    key, m_len, table_size = map(int, input().split())

    # ยกกำลังสองตามทฤษฎี Mid-Square
    result = str(key ** 2)
    total_len = len(result)

    # ตัดเลขตรงกลาง ปัดเศษลงเมื่อไม่ลงตัวเหมือนการบ้าน EX_25
    start_idx = (total_len - m_len) // 2
    end_idx = start_idx + m_len
    middle = result[start_idx:end_idx]

    slot = int(middle) % table_size

    print(middle)
    print(slot)


