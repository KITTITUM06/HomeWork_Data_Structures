# ข้อที่ 2: HEAP - ตรวจสอบความสัมพันธ์ Parent และ Children ตาม Index
# (ล้อตามสูตร Index ในสไลด์ Heap หน้า 3: p//2, 2p, 2p+1)
# ==============================================================================
# [คำอธิบายโจทย์]
# - รับ input บรรทัดเดียว: ชุดตัวเลขใน Min Heap และเลข index เป้าหมาย (อยู่ตัวสุดท้ายสุด)
# - บรรทัดที่ 1: แสดงค่าของ Left Child และ Right Child คั่นด้วยเว้นวรรค (ถ้าไม่มีแสดง None)
# - บรรทัดที่ 2: แสดงค่าของ Parent (ถ้าเป็น root หรือไม่มีแสดง None)

# [ตัวอย่าง Input]
# 5 9 11 14 18 19 21 2
# (ตัวเลขหน้าคือ Heap, ตัวสุดท้ายคือเลข 2 หมายถึง index ที่ 2 ซึ่งคือเลข 9)

# [ตัวอย่าง Output]
# 14 18
# 5
# ==============================================================================
def q2_homework_level_heap():
    data = list(map(int, input().split()))
    # ตัวเลขชุดข้อมูลอยู่ด้านหน้า (ใส่ dummy 0 ไว้ index 0 เพื่อให้ root เริ่มที่ 1)
    heap = [0] + data[:-1]
    target = data[-1]        # ตัวสุดท้ายคือ index ที่ต้องการตรวจสอบ
    size = len(heap) - 1

    # คำนวณตามสูตรสไลด์
    parent = heap[target // 2] if target // 2 > 0 else "None"
    left = heap[target * 2] if target * 2 <= size else "None"
    right = heap[target * 2 + 1] if target * 2 + 1 <= size else "None"

    print(str(left) + " " + str(right))
    print(parent)


