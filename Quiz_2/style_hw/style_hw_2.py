# ข้อ 1.3: Linear Probing Insert พร้อมนับการชน (Collisions) [เต็ง 2]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์]
# นำชุดตัวเลขมาหยอดลงในตารางแฮช หากช่องนั้นมีข้อมูลอยู่แล้ว (เกิดการชน)
# ให้นับจำนวนครั้งที่ชนเพิ่ม 1 และขยับหาช่องว่างถัดไปทีละ 1 ช่อง: (pos + 1) % size
# บรรทัดที่ 1: แสดงจำนวนครั้งที่เกิดการชน (Collisions) ทั้งหมด
# บรรทัดที่ 2: แสดงสภาพตารางแฮชที่บรรจุข้อมูลเสร็จสมบูรณ์
#
# [ตัวอย่าง Input/Output]
# Input:  77 44 55 20 26 93 17 31 54 11
#         (ชุดตัวเลขข้างหน้าคือข้อมูลที่จะหยอด, ตัวสุดท้าย 11 คือขนาดตาราง)
# Output: 3
#         77 44 55 20 26 93 17 None None 31 54
# ------------------------------------------------------------------------------
def run_q1_hash_linear_probing():
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    table = [None] * table_size
    collisions = 0

    for item in items:
        pos = item % table_size
        steps = 0
        while table[pos] is not None and steps < table_size:
            collisions += 1
            pos = (pos + 1) % table_size
            steps += 1
        if table[pos] is None:
            table[pos] = item

    print(collisions)
    print(" ".join(map(str, table)))


