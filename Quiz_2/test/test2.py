# ข้อที่ 2: [Binary Heap] Insert and PercUp Swap Count
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# รับสภาพ Min Heap เดิมเข้ามา และรับค่าใหม่ที่ต้องการแทรก (Insert)
# จุดเด่นการรับ Input:
# รับตัวเลขชุดเดียวในบรรทัดเดียว
# - ตัวเลขตั้งแต่ตัวแรกจนถึงตัวรองสุดท้าย = โหนดใน Min Heap เดิม
# - ตัวเลขตัวสุดท้าย = ค่าใหม่ที่ต้องการแทรกเข้าไป (new_val)
#
# การทำงาน:
# 1. นำ new_val ต่อท้ายสุดของฮีพ (append)
# 2. ทำ percUp เปรียบเทียบกับพ่อ (i // 2) ถ้าลูกน้อยกว่าพ่อให้สลับค่า (Swap)
# 3. นับจำนวนครั้งที่มีการสลับค่าเกิดขึ้นจริง
#
# การแสดงผล:
# บรรทัดที่ 1: แสดงจำนวนครั้งที่มีการสลับค่า (Swaps)
# บรรทัดที่ 2: แสดงสภาพ Min Heap ที่เหลือทั้งหมด คั่นด้วยเว้นวรรค
#
# [ตัวอย่าง Input]
# 10 20 15 30 40 50 60 12
# (Min Heap เดิมคือ 10 ถึง 60, ค่าใหม่ที่แทรกคือ 12)
#
# [การคำนวณเบื้องหลัง (Trace)]
# Heap เดิมใส่ dummy: [0, 10, 20, 15, 30, 40, 50, 60]
# แทรก 12 ต่อท้าย -> อยู่ที่ index 8
# - รอบ 1 (i=8): พ่ออยู่ที่ index 4 (ค่า 30) -> 12 < 30 -> สลับ (Swap 1) -> ย้ายไป i=4
# - รอบ 2 (i=4): พ่ออยู่ที่ index 2 (ค่า 20) -> 12 < 20 -> สลับ (Swap 2) -> ย้ายไป i=2
# - รอบ 3 (i=2): พ่ออยู่ที่ index 1 (ค่า 10) -> 12 > 10 -> ไม่สลับ หยุดลูป
# สรุปเกิดการสลับ 2 ครั้ง
#
# [ตัวอย่าง Output]
# 2
# 10 12 15 20 40 50 60 30
# ==============================================================================
def run_mock2_q2_insert_swaps():
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]  # ใส่ dummy 0 เพื่อให้ Root เริ่มดัชนี 1[cite: 2]
    new_val = data[-1]

    heap.append(new_val)
    i = len(heap) - 1
    swaps = 0

    # ลูป percUp ดันขึ้นเปรียบเทียบกับพ่อ (i // 2)[cite: 2]
    while i // 2 > 0:
        if heap[i] < heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            swaps += 1
            i = i // 2
        else:
            break

    print(swaps)
    print(" ".join(map(str, heap[1:])))


