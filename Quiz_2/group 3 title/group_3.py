# ข้อที่ 1: หมวด HASH (เต็ง 3 - Quadratic Probing ชนแล้วกระโดดยกกำลังสอง)
# อ้างอิงสไลด์: 09,12-Binary Tree and Traversal.pdf หน้า 15
# ==============================================================================
# [คำอธิบายโจทย์]
# รับ input บรรทัดเดียว: ชุดตัวเลขที่ต้องการหยอดลงตาราง โดย "ตัวสุดท้ายคือขนาดตาราง"
# หากเกิดการชน ให้กระโดดแบบยกกำลังสอง: rehash(h) = (h + k**2) % size (k = 1, 2, 3, ...)
# แสดงผลลัพธ์: สภาพตารางแฮชทั้งหมด คั่นด้วยเว้นวรรค (ช่องว่างแสดงคำว่า None)
#
# [ตัวอย่าง Input]
# 77 44 55 20 26 93 17 31 54 11
# (ขนาดตารางคือ 11 ตัวสุดท้าย)
#
# [ตัวอย่าง Output]
# 77 44 20 55 26 93 17 None None 31 54
# (44 ชน 77 ที่ช่อง 0 กระโดด +1^2 ไปช่อง 1, 55 ชน 77 กระโดด +1^2 ซ้ำ -> +2^2 ไปช่อง 4)
# ==============================================================================
def q1_hash_quadratic_probing():
    data = list(map(int, input().split()))
    items = data[:-1]
    table_size = data[-1]

    table = [None] * table_size

    for item in items:
        h = item % table_size
        pos = h
        k = 1
        # ชนครั้งแรก +1^2, ชนครั้งที่สอง +2^2, ชนครั้งที่สาม +3^2
        while table[pos] is not None:
            pos = (h + (k ** 2)) % table_size
            k = k + 1
        table[pos] = item

    print(" ".join(map(str, table)))


