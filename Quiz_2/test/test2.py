# ข้อที่ 1: [Hash Table] Separate Chaining Chain Length
# ==============================================================================
# [คำอธิบายโจทย์อย่างละเอียด]
# หยอดข้อมูลลงตารางแฮชโดยใช้เทคนิค Separate Chaining (หากชนให้ต่อ List ในช่องนั้น)
# จุดเด่นการรับ Input:
# รับข้อมูลเป็นชุดตัวเลขยาวๆ ในบรรทัดเดียว คั่นด้วย spacebar
# - ตัวเลขก้อนหน้าทั้งหมด (items) = ข้อมูลที่จะหยอดลงตาราง
# - ตัวเลขตัวรองสุดท้าย (target_idx) = หมายเลขช่อง (Index) ที่โจทย์ต้องการตรวจสอบ
# - ตัวเลขตัวสุดท้าย (table_size) = ขนาดของตารางแฮช
#
# การแสดงผล:
# บรรทัดที่ 1: แสดงข้อมูลทั้งหมดที่อยู่ในช่อง target_idx เรียงตามลำดับ คั่นด้วย ' -> '
#              (หากช่องนั้นไม่มีข้อมูลเลย ให้แสดงคำว่า 'Empty')
# บรรทัดที่ 2: แสดงความยาว (จำนวนข้อมูล) ในช่อง target_idx นั้น
#
# [ตัวอย่าง Input]
# 10 22 31 4 15 28 17 88 59 0 11
# (ข้อมูลคือ 10 ถึง 59, ตรวจสอบช่องที่ 0, ขนาดตารางคือ 11)
#
# [การคำนวณเบื้องหลัง (Trace)]
# นำข้อมูลมา mod 11:
# 10 % 11 = 10
# 22 % 11 = 0  -> ลงช่อง 0 ตัวที่ 1
# 31 % 11 = 9
# 4 % 11  = 4
# 15 % 11 = 4
# 28 % 11 = 6
# 17 % 11 = 6
# 88 % 11 = 0  -> ลงช่อง 0 ตัวที่ 2 (ต่อท้าย 22)
# 59 % 11 = 4
# สรุปในช่องที่ 0 มีข้อมูลคือ: [22, 88] ความยาวเท่ากับ 2
#
# [ตัวอย่าง Output]
# 22 -> 88
# 2
# ==============================================================================
def run_mock2_q1_chaining():
    # เทคนิคแกะ Input: ตัดก้อนหน้า, ตัวรองสุดท้าย, และตัวสุดท้าย
    data = list(map(int, input().split()))
    items = data[:-2]
    target_idx = data[-2]
    table_size = data[-1]

    # สร้างตารางที่แต่ละช่องเก็บ List ว่าง
    table = [[] for _ in range(table_size)]
    for item in items:
        pos = item % table_size
        table[pos].append(item)

    # แสดงผลตามเงื่อนไข
    if len(table[target_idx]) == 0:
        print("Empty")
    else:
        print(" -> ".join(map(str, table[target_idx])))

    print(len(table[target_idx]))


