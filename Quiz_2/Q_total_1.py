# ข้อ 2.2: Insert + percUp (เพิ่มข้อมูลต่อท้ายแล้วดันขึ้นเปรียบเทียบกับพ่อ) [เต็ง 2]
# ------------------------------------------------------------------------------
# [คำอธิบายโจทย์อย่างละเอียด]
# แทรกค่าใหม่เข้าไปใน Min Heap:
# 1. นำค่าใหม่ต่อท้ายสุดของฮีพ (append เข้า List)
# 2. ทำกระบวนการ percUp โดยเปรียบเทียบค่าของตัวเองกับโหนดพ่อ (ดัชนี i // 2)
# 3. ถ้าค่าตัวเองน้อยกว่าพ่อ ให้สลับที่กับพ่อ แล้วขยับตำแหน่งขึ้นไปชั้นบนเรื่อยๆ จนถึง Root[cite: 2]
#
# [ตัวอย่าง Input แบบ 1 บรรทัด] (ตัวท้ายสุดคือเลข 7 ที่ต้องการแทรก)
# 5 9 11 14 18 19 21 33 17 27 7
# [ตัวอย่าง Input แบบ 2 บรรทัด]
# 5 9 11 14 18 19 21 33 17 27
# 7
#
# [ตัวอย่าง Output]
# 5 7 11 14 9 19 21 33 17 27 18
# ------------------------------------------------------------------------------
def q2_2_heap_insert():
    # --- กรณีรับ 1 บรรทัด (ตัวท้ายคือค่าใหม่) ---
    data = list(map(int, input().split()))
    heap = [0] + data[:-1]
    new_val = data[-1]

    # --- กรณีรับ 2 บรรทัด ---
    # heap = [0] + list(map(int, input().split()))
    # new_val = int(input().strip())

    heap.append(new_val)
    i = len(heap) - 1

    # ดันค่าขึ้น (percUp) เปรียบเทียบกับพ่อ (i // 2)[cite: 2]
    while i // 2 > 0:
        if heap[i] < heap[i // 2]:
            heap[i], heap[i // 2] = heap[i // 2], heap[i]
            i = i // 2
        else:
            break

    print(" ".join(map(str, heap[1:])))


